class CBackend:
    name = "c"

    def __init__(self) -> None:
        self.program: ir.IRProgram | None = None
        self.structs: dict[str, ir.IRStructDef] = {}
        self.native_struct_names: dict[str, str] = {}
        self.classes: dict[Type, ir.IRClassDef] = {}
        self.function_refs: dict[tuple[str, FunctionType], str] = {}
        self.emitted_types: set[Type] = set()
        self.emitting_types: set[Type] = set()
        self.type_lines: list[str] = []
        self.temp_counter = 0
        self.current_function: ir.IRFunction | None = None
        self.current_closure: ir.IRClosureDef | None = None
        self.catch_targets: list[tuple[str | None, Type]] = []
        self.spawn_sites: dict[int, ir.IRSpawn] = {}
        self.metadata_uses: set[tuple[str, str]] = set()
        self.managed_scopes: list[list[tuple[str, Type]]] = []
        self.deferred_scopes: list[list[list[str]]] = []
        self.loop_scope_depths: list[int] = []

    def emit(self, program: ir.IRProgram, *, include_main: bool = True) -> str:
        self.program = program
        self.structs = {item.name: item for item in program.structs}
        self.native_struct_names = {
            item.name: item.native_name
            for item in program.structs
            if item.native_name is not None
        }
        self.classes = {item.typ: item for item in program.classes}
        self.emitted_types.clear()
        self.emitting_types.clear()
        self.type_lines.clear()
        self.temp_counter = 0
        self.metadata_uses.clear()
        self.spawn_sites = self.collect_spawn_sites(program)
        self.function_refs = self.collect_function_refs(program)

        lines = ["// Generated by the ZyenLang 0.3 typed C backend."]
        if "threads" in program.features:
            lines.append("#define ZY2_ENABLE_THREADS 1")
        lines.extend(["#define ZY2_RUNTIME_IMPLEMENTATION 1", '#include "zy2_runtime.h"', ""])
        for struct in program.structs:
            lines.append(f"typedef struct {self.struct_tag(struct.name)} {self.struct_c_name(struct.name)};")
        for class_def in program.classes:
            payload = self.class_payload_name(class_def.typ)
            handle = self.class_c_name(class_def.typ)
            tag = self.class_handle_tag(class_def.typ)
            lines.extend(
                [
                    f"typedef struct {payload} {payload};",
                    f"typedef struct {tag} {handle};",
                    f"struct {tag} {{ {payload}* data; zy2_ArcControl* owner; }};",
                    f"static inline ZY2_MAYBE_UNUSED {handle} {handle}_retain({handle} value);",
                    f"static inline ZY2_MAYBE_UNUSED void {handle}_release({handle} value);",
                ]
            )
            self.emitted_types.add(class_def.typ)
        if program.structs or program.classes:
            lines.append("")

        for typ in self.collect_program_types(program):
            self.emit_type_definition(typ)
        for class_def in program.classes:
            self.emit_class_type_definition(class_def)
        for closure in program.closures:
            self.emit_closure_type_definition(closure)
        lines.extend(self.type_lines)
        if self.type_lines:
            lines.append("")

        metadata_lines = self.emit_struct_metadata_tables()
        lines.extend(metadata_lines)
        if metadata_lines:
            lines.append("")

        for function in program.extern_functions:
            lines.append(self.extern_signature(function) + ";")
        if program.extern_functions:
            lines.append("")
        for function in program.functions:
            lines.append(self.function_signature(function) + ";")
        for closure in program.closures:
            lines.append(self.closure_signature(closure) + ";")
        lines.append("")

        for (target, function_type), adapter in self.function_refs.items():
            lines.extend(self.emit_function_adapter(target, function_type, adapter))
            lines.append("")

        for class_def in program.classes:
            lines.extend(self.emit_class_helpers(class_def))
            lines.append("")

        for closure in program.closures:
            lines.extend(self.emit_closure_helpers(closure))
            lines.append("")

        for spawn in self.spawn_sites.values():
            lines.extend(self.emit_spawn_helper(spawn))
            lines.append("")

        for function in program.functions:
            lines.extend(self.emit_function(function))
            lines.append("")

        for closure in program.closures:
            lines.extend(self.emit_closure_function(closure))
            lines.append("")

        if include_main:
            main = next(item for item in program.functions if item.name == "main" and item.receiver_type is None)
            lines.extend(self.emit_main_wrapper(main))
            lines.append("")
        return "\n".join(lines)

    def collect_function_refs(self, program: ir.IRProgram) -> dict[tuple[str, FunctionType], str]:
        found: dict[tuple[str, FunctionType], str] = {}

        def visit(value: object) -> None:
            if isinstance(value, ir.IRFunctionRef):
                assert isinstance(value.typ, FunctionType)
                key = (value.target, value.typ)
                found.setdefault(
                    key,
                    f"__zy3_fn_adapter_{self.ident(value.target)}_{self.type_slug(value.typ)}",
                )
                return
            if isinstance(value, tuple):
                for item in value:
                    visit(item)
                return
            if is_dataclass(value) and value.__class__.__module__ == ir.__name__:
                for item in dataclass_fields(value):
                    if item.name not in {"typ", "span"}:
                        visit(getattr(value, item.name))

        visit(program.functions)
        visit(program.classes)
        return found

    def emit_function_adapter(self, target: str, typ: FunctionType, adapter: str) -> list[str]:
        params = ["void* env"]
        params.extend(f"{self.c_type(item)} arg_{index}" for index, item in enumerate(typ.params))
        arguments = ", ".join(f"arg_{index}" for index in range(len(typ.params)))
        lines = [
            f"static ZY2_MAYBE_UNUSED {self.c_type(typ.return_type)} {adapter}({', '.join(params)}) {{",
            "    (void)env;",
        ]
        call = f"{target}({arguments})"
        if typ.return_type == VOID:
            lines.extend([f"    {call};", "    return;", "}"])
        else:
            lines.extend([f"    return {call};", "}"])
        return lines

    def collect_spawn_sites(self, program: ir.IRProgram) -> dict[int, ir.IRSpawn]:
        found: dict[int, ir.IRSpawn] = {}

        def expression(value: ir.IRExpr) -> None:
            if isinstance(value, ir.IRSpawn):
                found[value.spawn_id] = value
                expression(value.call)
            elif isinstance(value, ir.IRAwait):
                expression(value.task)
            elif isinstance(value, ir.IROptionalSome):
                expression(value.value)
            elif isinstance(value, ir.IROptionalValue):
                expression(value.optional)
            elif isinstance(value, ir.IRBorrow):
                expression(value.value)
            elif isinstance(value, ir.IRReferencePlace):
                expression(value.reference)
            elif isinstance(value, ir.IRReferenceCoerce):
                expression(value.reference)
            elif isinstance(value, ir.IRReferenceValue):
                expression(value.reference)
            elif isinstance(value, ir.IRClosure):
                for _, capture in value.captures:
                    expression(capture)
            elif isinstance(value, ir.IRFString):
                for item in value.parts:
                    if isinstance(item, ir.IRExpr):
                        expression(item)
            elif isinstance(value, ir.IRUnary):
                expression(value.operand)
            elif isinstance(value, ir.IRBinary):
                expression(value.left)
                expression(value.right)
            elif isinstance(value, ir.IRCast):
                expression(value.value)
            elif isinstance(value, ir.IRField):
                expression(value.receiver)
            elif isinstance(value, ir.IRIndirectCall):
                expression(value.callee)
                for arg in value.args:
                    expression(arg)
            elif isinstance(value, ir.IRCall):
                for arg in value.args:
                    expression(arg)
            elif isinstance(value, (ir.IRTuple, ir.IRList)):
                for item in value.items:
                    expression(item)
            elif isinstance(value, ir.IRStruct):
                for _, item in value.fields:
                    expression(item)
            elif isinstance(value, ir.IRClassNew):
                for item in value.args:
                    expression(item)
                for _, item in value.defaults:
                    expression(item)
            elif isinstance(value, ir.IRStructMetadata):
                expression(value.receiver)
            elif isinstance(value, ir.IRErrorStack):
                expression(value.error)
            elif isinstance(value, ir.IRBox):
                expression(value.value)
            elif isinstance(value, ir.IRBoxValue):
                expression(value.box)
            elif isinstance(value, ir.IRArcCount):
                expression(value.value)
            elif isinstance(value, ir.IRCatch):
                expression(value.value)
                block(value.handler)

        def statement(value: ir.IRStmt) -> None:
            if isinstance(value, ir.IRLet):
                expression(value.value)
            elif isinstance(value, (ir.IRReturn, ir.IRRecover)) and value.value is not None:
                expression(value.value)
            elif isinstance(value, ir.IRStop):
                expression(value.error)
            elif isinstance(value, ir.IRIf):
                expression(value.condition)
                block(value.then_block)
                if value.else_block:
                    block(value.else_block)
            elif isinstance(value, ir.IRIfLet):
                expression(value.value)
                block(value.then_block)
                if value.else_block:
                    block(value.else_block)
            elif isinstance(value, ir.IRWhile):
                expression(value.condition)
                block(value.body)
            elif isinstance(value, ir.IRAssign):
                expression(value.target)
                expression(value.value)
            elif isinstance(value, ir.IRDefer):
                expression(value.call)
            elif isinstance(value, ir.IRExprStmt):
                expression(value.value)

        def block(value: ir.IRBlock) -> None:
            for item in value.statements:
                statement(item)

        for function in program.functions:
            block(function.body)
        return found

    def collect_program_types(self, program: ir.IRProgram) -> list[Type]:
        found: list[Type] = []
        seen: set[Type] = set()

        def add(typ: Type) -> None:
            if typ in seen:
                return
            seen.add(typ)
            found.append(typ)
            if isinstance(typ, NamedType):
                for arg in typ.args:
                    add(arg)
            elif isinstance(typ, TupleType):
                for item in typ.items:
                    add(item)
            elif isinstance(typ, OptionalType):
                add(typ.inner)
            elif isinstance(typ, FunctionType):
                for item in typ.params:
                    add(item)
                add(typ.return_type)
            elif isinstance(typ, ReferenceType):
                add(typ.inner)

        def expression(value: ir.IRExpr) -> None:
            add(value.typ)
            if isinstance(value, ir.IROptionalSome):
                expression(value.value)
            elif isinstance(value, ir.IROptionalValue):
                expression(value.optional)
            elif isinstance(value, ir.IRBorrow):
                expression(value.value)
            elif isinstance(value, ir.IRReferencePlace):
                expression(value.reference)
            elif isinstance(value, ir.IRReferenceCoerce):
                expression(value.reference)
            elif isinstance(value, ir.IRReferenceValue):
                expression(value.reference)
            elif isinstance(value, ir.IRClosure):
                for _, capture in value.captures:
                    expression(capture)
            elif isinstance(value, ir.IRFString):
                for item in value.parts:
                    if isinstance(item, ir.IRExpr):
                        expression(item)
            elif isinstance(value, ir.IRUnary):
                expression(value.operand)
            elif isinstance(value, ir.IRBinary):
                expression(value.left)
                expression(value.right)
            elif isinstance(value, ir.IRCast):
                expression(value.value)
            elif isinstance(value, ir.IRField):
                expression(value.receiver)
            elif isinstance(value, ir.IRIndirectCall):
                expression(value.callee)
                for arg in value.args:
                    expression(arg)
            elif isinstance(value, ir.IRCall):
                if value.throws:
                    add(value.throws)
                    add(self.result_marker(value.typ))
                for arg in value.args:
                    expression(arg)
            elif isinstance(value, (ir.IRTuple, ir.IRList)):
                for item in value.items:
                    expression(item)
            elif isinstance(value, ir.IRStruct):
                for _, item in value.fields:
                    expression(item)
            elif isinstance(value, ir.IRClassNew):
                for item in value.args:
                    expression(item)
                for _, item in value.defaults:
                    expression(item)
            elif isinstance(value, ir.IRStructMetadata):
                self.metadata_uses.add((value.struct_name, value.category))
                expression(value.receiver)
            elif isinstance(value, ir.IRErrorStack):
                expression(value.error)
            elif isinstance(value, ir.IRBox):
                expression(value.value)
            elif isinstance(value, ir.IRBoxValue):
                expression(value.box)
            elif isinstance(value, ir.IRArcCount):
                expression(value.value)
            elif isinstance(value, ir.IRCatch):
                expression(value.value)
                block(value.handler)
            elif isinstance(value, ir.IRSpawn):
                expression(value.call)
            elif isinstance(value, ir.IRAwait):
                expression(value.task)

        def statement(value: ir.IRStmt) -> None:
            if isinstance(value, ir.IRLet):
                for typ in value.types:
                    add(typ)
                expression(value.value)
            elif isinstance(value, (ir.IRReturn, ir.IRRecover)) and value.value is not None:
                expression(value.value)
            elif isinstance(value, ir.IRStop):
                expression(value.error)
            elif isinstance(value, ir.IRIf):
                expression(value.condition)
                block(value.then_block)
                if value.else_block:
                    block(value.else_block)
            elif isinstance(value, ir.IRIfLet):
                expression(value.value)
                add(value.inner_type)
                block(value.then_block)
                if value.else_block:
                    block(value.else_block)
            elif isinstance(value, ir.IRWhile):
                expression(value.condition)
                block(value.body)
            elif isinstance(value, ir.IRAssign):
                expression(value.target)
                expression(value.value)
            elif isinstance(value, ir.IRDefer):
                expression(value.call)
            elif isinstance(value, ir.IRExprStmt):
                expression(value.value)

        def block(value: ir.IRBlock) -> None:
            for item in value.statements:
                statement(item)

        for struct in program.structs:
            add(NamedType(struct.name))
            for field in struct.fields:
                add(field.typ)
                if field.default:
                    expression(field.default)
        for class_def in program.classes:
            add(class_def.typ)
            for field in class_def.fields:
                add(field.typ)
                if field.default:
                    expression(field.default)
        for closure in program.closures:
            add(closure.typ)
            for param in closure.params:
                add(param.typ)
            for _, capture_type in closure.captures:
                add(capture_type)
            block(closure.body)
        for function in program.functions:
            add(function.return_type)
            if function.throws:
                add(function.throws)
                add(self.result_marker(function.return_type))
            for param in function.params:
                add(param.typ)
            block(function.body)
        for function in program.extern_functions:
            add(function.return_type)
            if function.throws:
                add(function.throws)
                add(self.result_marker(function.return_type))
            for param in function.params:
                add(param.typ)
        return found

    def result_marker(self, value_type: Type) -> NamedType:
        return NamedType("__Result", (value_type, ERROR))

    def emit_type_definition(self, typ: Type) -> None:
        if typ in self.emitted_types or isinstance(typ, PrimitiveType):
            return
        if typ in self.emitting_types:
            raise ValueError(f"recursive by-value type `{typ.display()}`")
        self.emitting_types.add(typ)
        try:
            if isinstance(typ, NamedType) and typ.name in self.structs:
                struct = self.structs[typ.name]
                for field in struct.fields:
                    self.emit_type_definition(field.typ)
                self.type_lines.append(f"struct {self.struct_tag(struct.name)} {{")
                for field in struct.fields:
                    self.type_lines.append(f"    {self.c_type(field.typ)} {self.ident(field.name)};")
                self.type_lines.append("};")
                self.type_lines.append("")
                if self.is_managed(typ):
                    name = self.type_name(typ)
                    self.type_lines.append(f"static inline ZY2_MAYBE_UNUSED {name} {name}_retain({name} value) {{")
                    for field in struct.fields:
                        if self.is_managed(field.typ):
                            field_name = self.ident(field.name)
                            self.type_lines.append(
                                f"    value.{field_name} = {self.retain_expr(f'value.{field_name}', field.typ)};"
                            )
                    self.type_lines.append("    return value;")
                    self.type_lines.append("}")
                    self.type_lines.append(f"static inline ZY2_MAYBE_UNUSED void {name}_release({name} value) {{")
                    for field in reversed(struct.fields):
                        if self.is_managed(field.typ):
                            self.type_lines.append(
                                f"    {self.release_stmt(f'value.{self.ident(field.name)}', field.typ)}"
                            )
                    self.type_lines.append("}")
                    self.type_lines.append("")
            elif isinstance(typ, FunctionType):
                for item in (*typ.params, typ.return_type):
                    if isinstance(item, FunctionType):
                        self.emit_type_definition(item)
                params = ", ".join(["void*", *(self.c_type(item) for item in typ.params)])
                self.type_lines.append(
                    f"typedef {self.c_type(typ.return_type)} (*{self.type_name(typ)}_call)({params});"
                )
                self.type_lines.append(f"typedef ZL_Function {self.type_name(typ)};")
                self.type_lines.append("")
            elif isinstance(typ, ReferenceType):
                self.emit_type_definition(typ.inner)
                name = self.type_name(typ)
                pointer = f"const {self.c_type(typ.inner)}*" if not typ.mutable else f"{self.c_type(typ.inner)}*"
                self.type_lines.extend(
                    [
                        f"typedef struct {name} {{",
                        f"    {pointer} data;",
                        "    zy2_ArcControl* pin;",
                        f"}} {name};",
                        f"static inline ZY2_MAYBE_UNUSED {name} {name}_retain({name} value) {{",
                        "    zy2_arc_retain(value.pin);",
                        "    return value;",
                        "}",
                        f"static inline ZY2_MAYBE_UNUSED void {name}_release({name} value) {{",
                        "    zy2_arc_release(value.pin);",
                        "}",
                        "",
                    ]
                )
            elif is_list(typ):
                element = typ.args[0]
                self.emit_type_definition(element)
                name = self.type_name(typ)
                storage = f"{name}_storage"
                release_item = self.release_stmt("storage->items[index]", element)
                retain_item = self.retain_expr("item", element)
                retain_old_item = self.retain_expr("old_items[index]", element)
                self.type_lines.extend(
                    [
                        f"typedef struct {storage} {{",
                        f"    {self.c_type(element)}* items;",
                        "    uintptr_t len;",
                        "    uintptr_t capacity;",
                        f"}} {storage};",
                        f"typedef struct {name} {{",
                        f"    {storage}* storage;",
                        f"    {self.c_type(element)}* borrowed_items;",
                        "    uintptr_t borrowed_len;",
                        "    zy2_ArcControl* owner;",
                        f"}} {name};",
                        "",
                        f"static inline ZY2_MAYBE_UNUSED void {name}_storage_drop(void* payload) {{",
                        f"    {storage}* storage = ({storage}*)payload;",
                        "    if (!storage) return;",
                        "    for (uintptr_t index = 0; index < storage->len; ++index) {",
                        f"        {release_item}",
                        "    }",
                        "    free(storage->items);",
                        "    free(storage);",
                        "}",
                        f"static inline ZY2_MAYBE_UNUSED {name} {name}_new(uintptr_t capacity) {{",
                        f"    {storage}* storage = ({storage}*)calloc(1, sizeof({storage}));",
                        "    if (!storage) zy2_arc_panic(\"cannot allocate List storage\");",
                        "    if (capacity > 0) {",
                        f"        storage->items = ({self.c_type(element)}*)calloc(capacity, sizeof({self.c_type(element)}));",
                        "        if (!storage->items) { free(storage); zy2_arc_panic(\"cannot allocate List data\"); }",
                        "        storage->capacity = capacity;",
                        "    }",
                        f"    return ({name}){{ .storage = storage, .owner = zy2_arc_new(storage, {name}_storage_drop) }};",
                        "}",
                        f"static inline ZY2_MAYBE_UNUSED {name} {name}_borrow({self.c_type(element)}* items, uintptr_t len) {{",
                        f"    return ({name}){{ .borrowed_items = items, .borrowed_len = len }};",
                        "}",
                        f"static inline ZY2_MAYBE_UNUSED {name} {name}_retain({name} value) {{",
                        "    zy2_arc_retain(value.owner);",
                        "    return value;",
                        "}",
                        f"static inline ZY2_MAYBE_UNUSED void {name}_release({name} value) {{",
                        "    zy2_arc_release(value.owner);",
                        "}",
                        f"static inline ZY2_MAYBE_UNUSED uintptr_t {name}_len({name} value) {{",
                        "    return value.storage ? value.storage->len : value.borrowed_len;",
                        "}",
                        f"static inline ZY2_MAYBE_UNUSED {self.c_type(element)}* {name}_items({name} value) {{",
                        "    return value.storage ? value.storage->items : value.borrowed_items;",
                        "}",
                        f"static inline ZY2_MAYBE_UNUSED void {name}_ensure_mutable({name}* value, uintptr_t extra) {{",
                        "    if (!value->owner) {",
                        f"        {self.c_type(element)}* old_items = value->borrowed_items;",
                        "        uintptr_t old_len = value->borrowed_len;",
                        "        uintptr_t initial = old_len + extra;",
                        "        if (initial < 4) initial = 4;",
                        f"        *value = {name}_new(initial);",
                        "        for (uintptr_t index = 0; index < old_len; ++index) {",
                        f"            value->storage->items[index] = {retain_old_item};",
                        "        }",
                        "        value->storage->len = old_len;",
                        "    } else if (zy2_arc_strong_count(value->owner) > 1u) {",
                        f"        {name} old_value = *value;",
                        f"        {self.c_type(element)}* old_items = old_value.storage->items;",
                        "        uintptr_t old_len = old_value.storage->len;",
                        "        uintptr_t initial = old_len + extra;",
                        "        if (initial < 4) initial = 4;",
                        f"        *value = {name}_new(initial);",
                        "        for (uintptr_t index = 0; index < old_len; ++index) {",
                        f"            value->storage->items[index] = {retain_old_item};",
                        "        }",
                        "        value->storage->len = old_len;",
                        f"        {name}_release(old_value);",
                        "    }",
                        "    uintptr_t required = value->storage->len + extra;",
                        "    if (required <= value->storage->capacity) return;",
                        "    uintptr_t capacity = value->storage->capacity ? value->storage->capacity : 4;",
                        "    while (capacity < required) {",
                        "        if (capacity > UINTPTR_MAX / 2) zy2_arc_panic(\"List capacity overflow\");",
                        "        capacity *= 2;",
                        "    }",
                        f"    {self.c_type(element)}* grown = ({self.c_type(element)}*)realloc(value->storage->items, capacity * sizeof({self.c_type(element)}));",
                        "    if (!grown) zy2_arc_panic(\"cannot grow List\");",
                        "    value->storage->items = grown;",
                        "    value->storage->capacity = capacity;",
                        "}",
                        f"static inline ZY2_MAYBE_UNUSED void {name}_push_copy({name}* value, {self.c_type(element)} item) {{",
                        f"    {name}_ensure_mutable(value, 1);",
                        f"    value->storage->items[value->storage->len++] = {retain_item};",
                        "}",
                        f"static inline ZY2_MAYBE_UNUSED void {name}_set_copy({name}* value, uintptr_t index, {self.c_type(element)} item) {{",
                        f"    {name}_ensure_mutable(value, 0);",
                        f"    {self.release_stmt('value->storage->items[index]', element)}",
                        f"    value->storage->items[index] = {retain_item};",
                        "}",
                        f"static inline ZY2_MAYBE_UNUSED void {name}_clear({name}* value) {{",
                        "    if (!value->owner) {",
                        f"        *value = {name}_new(0);",
                        "        return;",
                        "    }",
                        "    if (zy2_arc_strong_count(value->owner) > 1u) {",
                        f"        {name} old_value = *value;",
                        f"        *value = {name}_new(0);",
                        f"        {name}_release(old_value);",
                        "        return;",
                        "    }",
                        "    for (uintptr_t index = 0; index < value->storage->len; ++index) {",
                        f"        {self.release_stmt('value->storage->items[index]', element)}",
                        "    }",
                        "    value->storage->len = 0;",
                        "}",
                        "",
                    ]
                )
                if element == STR:
                    self.type_lines.extend(
                        [
                            f"static inline ZY2_MAYBE_UNUSED {name} {name}_from_utf8(ZL_String text) {{",
                            "    const unsigned char* bytes = (const unsigned char*)zl_string_data(text);",
                            "    size_t byte_len = text.byte_len;",
                            "    size_t offset = 0u;",
                            "    uintptr_t count = 0u;",
                            "    while (offset < byte_len) {",
                            "        size_t width = zy2_utf8_character_size(bytes + offset, byte_len - offset);",
                            "        if (width == 0u) zy2_arc_panic(\"STR_TO_LIST__ expects valid UTF-8\");",
                            "        offset += width;",
                            "        count += 1u;",
                            "    }",
                            f"    {name} result = {name}_new(count);",
                            "    if (count == 0u) return result;",
                            "    offset = 0u;",
                            "    uintptr_t index = 0u;",
                            "    while (offset < byte_len) {",
                            "        size_t width = zy2_utf8_character_size(bytes + offset, byte_len - offset);",
                            "        result.storage->items[index++] = zl_string_copy_n((const char*)bytes + offset, width);",
                            "        offset += width;",
                            "    }",
                            "    result.storage->len = count;",
                            "    return result;",
                            "}",
                            "",
                        ]
                    )
            elif is_task(typ):
                self.emit_type_definition(typ.args[0])
                self.type_lines.extend(
                    [
                        f"typedef struct {self.type_name(typ)} {{",
                        "    zy2_Task* control;",
                        f"}} {self.type_name(typ)};",
                        "",
                    ]
                )
            elif is_box(typ):
                inner = typ.args[0]
                self.emit_type_definition(inner)
                name = self.type_name(typ)
                drop = f"{name}_payload_drop"
                self.type_lines.extend(
                    [
                        f"typedef struct {name} {{",
                        f"    {self.c_type(inner)}* data;",
                        "    zy2_ArcControl* owner;",
                        f"}} {name};",
                        "",
                        f"static inline ZY2_MAYBE_UNUSED void {drop}(void* raw_payload) {{",
                        f"    {self.c_type(inner)}* payload = ({self.c_type(inner)}*)raw_payload;",
                        "    if (!payload) return;",
                        f"    {self.release_stmt('*payload', inner)}",
                        "    free(payload);",
                        "}",
                        f"static inline ZY2_MAYBE_UNUSED {name} {name}_new({self.c_type(inner)} value) {{",
                        f"    {self.c_type(inner)}* payload = ({self.c_type(inner)}*)malloc(sizeof({self.c_type(inner)}));",
                        "    if (!payload) zy2_arc_panic(\"cannot allocate Box payload\");",
                        "    *payload = value;",
                        f"    return ({name}){{ .data = payload, .owner = zy2_arc_new(payload, {drop}) }};",
                        "}",
                        f"static inline ZY2_MAYBE_UNUSED {name} {name}_retain({name} value) {{",
                        "    zy2_arc_retain(value.owner);",
                        "    return value;",
                        "}",
                        f"static inline ZY2_MAYBE_UNUSED void {name}_release({name} value) {{",
                        "    zy2_arc_release(value.owner);",
                        "}",
                        "",
                    ]
                )
            elif isinstance(typ, OptionalType):
                self.emit_type_definition(typ.inner)
                name = self.type_name(typ)
                self.type_lines.extend(
                    [
                        f"typedef struct {name} {{",
                        "    bool has_value;",
                        f"    {self.c_type(typ.inner)} value;",
                        f"}} {name};",
                        "",
                    ]
                )
                if self.is_managed(typ.inner):
                    self.type_lines.extend(
                        [
                            f"static inline ZY2_MAYBE_UNUSED {name} {name}_retain({name} value) {{",
                            f"    if (value.has_value) value.value = {self.retain_expr('value.value', typ.inner)};",
                            "    return value;",
                            "}",
                            f"static inline ZY2_MAYBE_UNUSED void {name}_release({name} value) {{",
                            f"    if (value.has_value) {self.release_stmt('value.value', typ.inner)}",
                            "}",
                            "",
                        ]
                    )
            elif isinstance(typ, TupleType):
                for item in typ.items:
                    self.emit_type_definition(item)
                name = self.type_name(typ)
                self.type_lines.append(f"typedef struct {name} {{")
                for index, item in enumerate(typ.items):
                    self.type_lines.append(f"    {self.c_type(item)} item_{index};")
                self.type_lines.append(f"}} {name};")
                self.type_lines.append("")
                if self.is_managed(typ):
                    self.type_lines.append(f"static inline ZY2_MAYBE_UNUSED {name} {name}_retain({name} value) {{")
                    for index, item in enumerate(typ.items):
                        if self.is_managed(item):
                            self.type_lines.append(
                                f"    value.item_{index} = {self.retain_expr(f'value.item_{index}', item)};"
                            )
                    self.type_lines.extend(["    return value;", "}"])
                    self.type_lines.append(f"static inline ZY2_MAYBE_UNUSED void {name}_release({name} value) {{")
                    for index, item in reversed(tuple(enumerate(typ.items))):
                        if self.is_managed(item):
                            self.type_lines.append(f"    {self.release_stmt(f'value.item_{index}', item)}")
                    self.type_lines.extend(["}", ""])
            elif isinstance(typ, NamedType) and typ.name == "__Result":
                value_type = typ.args[0]
                self.emit_type_definition(value_type)
                self.type_lines.append(f"typedef struct {self.type_name(typ)} {{")
                self.type_lines.append("    bool ok;")
                if value_type != VOID:
                    self.type_lines.append(f"    {self.c_type(value_type)} value;")
                self.type_lines.append("    zy2_Error error;")
                self.type_lines.append(f"}} {self.type_name(typ)};")
                self.type_lines.append("")
            else:
                raise ValueError(f"C backend does not yet support `{typ.display()}`")
            self.emitted_types.add(typ)
        finally:
            self.emitting_types.remove(typ)

    def emit_class_type_definition(self, class_def: ir.IRClassDef) -> None:
        typ = class_def.typ
        payload = self.class_payload_name(typ)
        handle = self.class_c_name(typ)
        drop = self.class_drop_name(typ)
        for field in class_def.fields:
            self.emit_type_definition(field.typ)
        self.type_lines.append(f"struct {payload} {{")
        for field in class_def.fields:
            self.type_lines.append(f"    {self.c_type(field.typ)} {self.ident(field.name)};")
        self.type_lines.append("};")
        self.type_lines.append(f"static ZY2_MAYBE_UNUSED void {drop}(void* raw_payload);")
        self.type_lines.append(f"static inline ZY2_MAYBE_UNUSED {handle} {handle}_retain({handle} value) {{")
        self.type_lines.append("    zy2_arc_retain(value.owner);")
        self.type_lines.append("    return value;")
        self.type_lines.append("}")
        self.type_lines.append(f"static inline ZY2_MAYBE_UNUSED void {handle}_release({handle} value) {{")
        self.type_lines.append("    zy2_arc_release(value.owner);")
        self.type_lines.append("}")
        self.type_lines.append("")

    def emit_class_helpers(self, class_def: ir.IRClassDef) -> list[str]:
        typ = class_def.typ
        payload = self.class_payload_name(typ)
        handle = self.class_c_name(typ)
        drop = self.class_drop_name(typ)
        lines = [f"static ZY2_MAYBE_UNUSED void {drop}(void* raw_payload) {{", f"    {payload}* data = ({payload}*)raw_payload;"]
        lines.append("    if (!data) return;")
        if class_def.deinitializer:
            lines.append(
                f"    {class_def.deinitializer}(({handle}){{ .data = data, .owner = NULL }});"
            )
        for field in reversed(class_def.fields):
            if self.is_managed(field.typ):
                lines.append(f"    {self.release_stmt(f'data->{self.ident(field.name)}', field.typ)}")
        lines.append("    free(data);")
        lines.append("}")
        return lines

    def closure_env_name(self, closure: ir.IRClosureDef) -> str:
        return f"{self.ident(closure.name)}_env"

    def closure_drop_name(self, closure: ir.IRClosureDef) -> str:
        return f"{self.ident(closure.name)}_env_drop"

    def emit_closure_type_definition(self, closure: ir.IRClosureDef) -> None:
        env = self.closure_env_name(closure)
        self.type_lines.append(f"typedef struct {env} {{")
        if closure.captures:
            for name, typ in closure.captures:
                self.type_lines.append(f"    {self.c_type(typ)} {self.ident(name)};")
        else:
            self.type_lines.append("    unsigned char unused;")
        self.type_lines.append(f"}} {env};")
        self.type_lines.append("")

    def emit_closure_helpers(self, closure: ir.IRClosureDef) -> list[str]:
        env = self.closure_env_name(closure)
        lines = [
            f"static void {self.closure_drop_name(closure)}(void* raw_payload) {{",
            f"    {env}* data = ({env}*)raw_payload;",
            "    if (!data) return;",
        ]
        for name, typ in reversed(closure.captures):
            if self.is_managed(typ):
                lines.append(f"    {self.release_stmt(f'data->{self.ident(name)}', typ)}")
        lines.extend(["    free(data);", "}"])
        return lines

    def closure_signature(self, closure: ir.IRClosureDef) -> str:
        params = ["void* __zy_env_raw"]
        params.extend(f"{self.c_type(param.typ)} {self.ident(param.name)}" for param in closure.params)
        assert isinstance(closure.typ, FunctionType)
        return f"static ZY2_MAYBE_UNUSED {self.c_type(closure.typ.return_type)} {closure.name}({', '.join(params)})"

    def emit_closure_function(self, closure: ir.IRClosureDef) -> list[str]:
        assert isinstance(closure.typ, FunctionType)
        synthetic = ir.IRFunction(
            closure.name,
            closure.name,
            closure.params,
            closure.typ.return_type,
            closure.body,
            "private",
        )
        self.current_function = synthetic
        self.current_closure = closure
        self.managed_scopes = []
        self.deferred_scopes = []
        self.loop_scope_depths = []
        env = self.closure_env_name(closure)
        try:
            lines = [self.closure_signature(closure) + " {", f"    {env}* __zy_env = ({env}*)__zy_env_raw;", "    (void)__zy_env;"]
            for param in closure.params:
                lines.append(f"    (void){self.ident(param.name)};")
            managed_params = tuple(param for param in closure.params if self.is_managed(param.typ))
            lines.extend(self.emit_block(closure.body, 1, managed_params=managed_params))
            if closure.typ.return_type == VOID:
                lines.append("    return;")
            else:
                lines.append(
                    f"    return {self.zero_value(closure.typ.return_type)}; /* unreachable after verified returns */"
                )
            lines.append("}")
            return lines
        finally:
            self.current_closure = None
            self.current_function = None

    def emit_function(self, function: ir.IRFunction) -> list[str]:
        self.current_function = function
        self.managed_scopes = []
        self.deferred_scopes = []
        self.loop_scope_depths = []
        try:
            lines = [self.function_signature(function) + " {"]
            for param in function.params:
                lines.append(f"    (void){self.ident(param.name)};")
            managed_params = tuple(param for param in function.params if self.is_managed(param.typ))
            lines.extend(self.emit_block(function.body, 1, managed_params=managed_params))
            if function.return_type == VOID and not function.throws:
                lines.append("    return;")
            elif function.return_type == VOID and function.throws:
                result = self.result_type(function.return_type)
                lines.append(f"    return ({result}){{ .ok = true }};")
            elif function.throws:
                result = self.result_type(function.return_type)
                fallback = self.temp("unreachable_result")
                lines.append(f"    {result} {fallback} = {{0}}; /* unreachable after verified returns */")
                lines.append(f"    {fallback}.ok = true;")
                lines.append(f"    return {fallback};")
            else:
                lines.append(
                    f"    return {self.zero_value(function.return_type)}; /* unreachable after verified returns */"
                )
            lines.append("}")
            return lines
        finally:
            self.current_function = None

    def function_signature(self, function: ir.IRFunction) -> str:
        return_type = self.result_type(function.return_type) if function.throws else self.c_type(function.return_type)
        params = ", ".join(f"{self.c_type(param.typ)} {self.ident(param.name)}" for param in function.params)
        if not params:
            params = "void"
        prefix = (
            "ZYENLANG_API "
            if function.exported and "::" not in function.name
            else "static ZY2_MAYBE_UNUSED "
            if function.visibility == "private"
            else ""
        )
        return f"{prefix}{return_type} {function.c_name}({params})"

    def extern_signature(self, function: ir.IRExternFunction) -> str:
        return_type = self.result_type(function.return_type) if function.throws else self.c_type(function.return_type)
        params = ", ".join(f"{self.c_type(param.typ)} {self.ident(param.name)}" for param in function.params)
        if not params:
            params = "void"
        return f"extern {return_type} {function.c_name}({params})"

    def emit_spawn_helper(self, expression: ir.IRSpawn) -> list[str]:
        result_type = expression.call.typ
        lines = [f"static void __zy2_spawn_{expression.spawn_id}(void* context, void* result) {{", "    (void)context;"]
        if result_type == VOID:
            lines.append("    (void)result;")
            lines.append(f"    {expression.call.target}();")
        else:
            lines.append(f"    *(({self.c_type(result_type)}*)result) = {expression.call.target}();")
        lines.append("}")
        return lines

    def emit_main_wrapper(self, main: ir.IRFunction) -> list[str]:
        lines = ["int main(int argc, char** argv) {", "    zy2_set_process_args(argc, argv);"]
        if main.throws:
            lines.append(f"    {self.result_type(main.return_type)} result = {main.c_name}();")
            lines.append("    if (!result.ok) zy2_unhandled_error(result.error);")
            lines.append("    int exit_code = (int)result.value;")
        else:
            lines.append(f"    int exit_code = (int){main.c_name}();")
        lines.append("    if (!zy2_arc_assert_clean()) return 101;")
        lines.append("    return exit_code;")
        lines.append("}")
        return lines

    def emit_block(
        self,
        block: ir.IRBlock,
        indent: int,
        *,
        managed_params: tuple[ir.IRParam, ...] = (),
        owned_params: tuple[ir.IRParam, ...] = (),
    ) -> list[str]:
        self.managed_scopes.append([])
        self.deferred_scopes.append([])
        lines: list[str] = []
        pad = "    " * indent
        try:
            for param in owned_params:
                self.managed_scopes[-1].append((self.ident(param.name), param.typ))
            for param in managed_params:
                name = self.ident(param.name)
                lines.append(f"{pad}{name} = {self.retain_expr(name, param.typ)};")
                self.managed_scopes[-1].append((name, param.typ))
            for statement in block.statements:
                lines.extend(self.emit_statement(statement, indent))
            lines.extend(self.cleanup_lines(len(self.managed_scopes) - 1, indent))
            return lines
        finally:
            self.deferred_scopes.pop()
            self.managed_scopes.pop()

    def emit_hoisted_declarations(self, block: ir.IRBlock, indent: int) -> list[str]:
        pad = "    " * indent
        lines: list[str] = []
        for local in block.hoisted:
            name = self.ident(local.name)
            lines.append(f"{pad}{self.c_type(local.typ)} {name} = {self.zero_value(local.typ)};")
            lines.append(f"{pad}(void){name};")
            if self.is_managed(local.typ):
                self.managed_scopes[-1].append((name, local.typ))
        return lines

    def emit_statement(self, statement: ir.IRStmt, indent: int) -> list[str]:
        pad = "    " * indent
        if isinstance(statement, ir.IRLet):
            value = self.emit_expr(statement.value)
            lines = [pad + line for line in value.prelude]
            if len(statement.names) == 1:
                typ = statement.types[0]
                name = self.ident(statement.names[0])
                initializer = self.take_or_retain(value, typ)
                lines.append(f"{pad}{self.c_type(typ)} {name} = {initializer};")
                lines.append(f"{pad}(void){name};")
                if self.is_managed(typ):
                    self.managed_scopes[-1].append((name, typ))
            else:
                temp = self.temp("tuple")
                lines.append(f"{pad}{self.c_type(statement.value.typ)} {temp} = {value.code};")
                for index, (name, typ) in enumerate(zip(statement.names, statement.types)):
                    field = f"{temp}.item_{index}"
                    initializer = field if value.owned else self.retain_expr(field, typ)
                    lines.append(f"{pad}{self.c_type(typ)} {self.ident(name)} = {initializer};")
                    lines.append(f"{pad}(void){self.ident(name)};")
                    if self.is_managed(typ):
                        self.managed_scopes[-1].append((self.ident(name), typ))
            return lines
        if isinstance(statement, ir.IRReturn):
            if statement.value is None:
                cleanup = self.cleanup_lines(0, indent)
                if self.current_function and self.current_function.throws:
                    return cleanup + [f"{pad}return ({self.result_type(VOID)}){{ .ok = true }};"]
                return cleanup + [f"{pad}return;"]
            value = self.emit_expr(statement.value)
            lines = [pad + line for line in value.prelude]
            return_type = self.current_function.return_type if self.current_function else statement.value.typ
            temp = self.temp("return")
            result_value = self.take_or_retain(value, return_type)
            lines.append(f"{pad}{self.c_type(return_type)} {temp} = {result_value};")
            lines.extend(self.cleanup_lines(0, indent))
            if self.current_function and self.current_function.throws:
                result = self.result_type(self.current_function.return_type)
                lines.append(f"{pad}return ({result}){{ .ok = true, .value = {temp} }};")
            else:
                lines.append(f"{pad}return {temp};")
            return lines
        if isinstance(statement, ir.IRStop):
            value = self.emit_expr(statement.error)
            lines = [pad + line for line in value.prelude]
            if not self.current_function or not self.current_function.throws:
                raise ValueError("verified IR contains stop in a non-throwing function")
            result = self.result_type(self.current_function.return_type)
            error_temp = self.temp("error")
            lines.append(f"{pad}zy2_Error {error_temp} = {value.code};")
            function_name = self.current_function.name if self.current_function else "<unknown>"
            lines.append(
                f"{pad}zy2_error_push_frame(&{error_temp}, zl_string_borrow({self.c_string(function_name)}), "
                f"zl_string_borrow({self.c_string(statement.span.source_name)}), {statement.span.line}, "
                f"{statement.span.column});"
            )
            lines.extend(self.cleanup_lines(0, indent))
            lines.append(f"{pad}return ({result}){{ .ok = false, .error = {error_temp} }};")
            return lines
        if isinstance(statement, ir.IRRecover):
            if not self.catch_targets:
                raise ValueError("verified IR contains recover outside catch")
            target, expected = self.catch_targets[-1]
            if statement.value is None:
                return [f"{pad}/* recovered void error */"]
            value = self.emit_expr(statement.value)
            lines = [pad + line for line in value.prelude]
            if target is None:
                if self.is_managed(statement.value.typ) and value.owned:
                    temp = self.temp("discarded_recovery")
                    lines.append(f"{pad}{self.c_type(statement.value.typ)} {temp} = {value.code};")
                    lines.append(f"{pad}{self.release_stmt(temp, statement.value.typ)}")
                else:
                    lines.append(f"{pad}(void)({value.code});")
            elif expected == VOID:
                lines.append(f"{pad}(void)({value.code});")
            else:
                lines.append(f"{pad}{target} = {self.take_or_retain(value, expected)};")
            return lines
        if isinstance(statement, ir.IRIf):
            condition = self.emit_expr(statement.condition)
            lines = self.emit_hoisted_declarations(statement.then_block, indent)
            if statement.else_block is not None:
                lines.extend(self.emit_hoisted_declarations(statement.else_block, indent))
            lines.extend(pad + line for line in condition.prelude)
            lines.append(f"{pad}if {self.control_condition(condition.code)} {{")
            lines.extend(self.emit_block(statement.then_block, indent + 1))
            if statement.else_block is not None:
                lines.append(f"{pad}}} else {{")
                lines.extend(self.emit_block(statement.else_block, indent + 1))
            lines.append(f"{pad}}}")
            return lines
        if isinstance(statement, ir.IRIfLet):
            value = self.emit_expr(statement.value)
            lines = self.emit_hoisted_declarations(statement.then_block, indent)
            if statement.else_block is not None:
                lines.extend(self.emit_hoisted_declarations(statement.else_block, indent))
            lines.extend(pad + line for line in value.prelude)
            temp = self.temp("optional")
            lines.append(f"{pad}{self.c_type(statement.value.typ)} {temp} = {value.code};")
            lines.append(f"{pad}if ({temp}.has_value) {{")
            lines.append(f"{pad}    {self.c_type(statement.inner_type)} {self.ident(statement.name)} = {temp}.value;")
            lines.append(f"{pad}    (void){self.ident(statement.name)};")
            lines.extend(self.emit_block(statement.then_block, indent + 1))
            if statement.else_block is not None:
                lines.append(f"{pad}}} else {{")
                lines.extend(self.emit_block(statement.else_block, indent + 1))
            lines.append(f"{pad}}}")
            return lines
        if isinstance(statement, ir.IRWhile):
            condition = self.emit_expr(statement.condition)
            lines = self.emit_hoisted_declarations(statement.body, indent)
            lines.append(f"{pad}while (true) {{")
            lines.extend("    " + pad + line for line in condition.prelude)
            lines.append(f"{pad}    if (!{self.control_condition(condition.code)}) break;")
            self.loop_scope_depths.append(len(self.managed_scopes))
            try:
                lines.extend(self.emit_block(statement.body, indent + 1))
            finally:
                self.loop_scope_depths.pop()
            lines.append(f"{pad}}}")
            return lines
        if isinstance(statement, ir.IRAssign):
            target = self.emit_expr(statement.target)
            value = self.emit_expr(statement.value)
            lines = [pad + line for line in target.prelude + value.prelude]
            if self.is_managed(statement.target.typ):
                temp = self.temp("assign")
                lines.append(
                    f"{pad}{self.c_type(statement.target.typ)} {temp} = {self.take_or_retain(value, statement.target.typ)};"
                )
                lines.append(f"{pad}{self.release_stmt(target.code, statement.target.typ)}")
                lines.append(f"{pad}{target.code} = {temp};")
            else:
                lines.append(f"{pad}{target.code} = {value.code};")
            return lines
        if isinstance(statement, ir.IRBreak):
            if not self.loop_scope_depths:
                raise ValueError("verified IR contains break outside a loop")
            return self.cleanup_lines(self.loop_scope_depths[-1], indent) + [f"{pad}break;"]
        if isinstance(statement, ir.IRContinue):
            if not self.loop_scope_depths:
                raise ValueError("verified IR contains continue outside a loop")
            return self.cleanup_lines(self.loop_scope_depths[-1], indent) + [f"{pad}continue;"]
        if isinstance(statement, ir.IRDrop):
            name = self.ident(statement.name)
            if self.is_managed(statement.typ):
                return [
                    f"{pad}{self.release_stmt(name, statement.typ)}",
                    f"{pad}{name} = {self.zero_value(statement.typ)};",
                ]
            raise ValueError("verified DROP__ contains an unmanaged type")
        if isinstance(statement, ir.IRDefer):
            return self.capture_defer(statement.call, indent)
        if isinstance(statement, ir.IRExprStmt):
            value = self.emit_expr(statement.value)
            lines = [pad + line for line in value.prelude]
            if self.is_managed(statement.value.typ) and value.owned:
                temp = self.temp("discard")
                lines.append(f"{pad}{self.c_type(statement.value.typ)} {temp} = {value.code};")
                lines.append(f"{pad}{self.release_stmt(temp, statement.value.typ)}")
            else:
                lines.append(f"{pad}(void)({value.code});")
            return lines
        raise ValueError(f"unsupported IR statement {type(statement).__name__}")

    def capture_defer(self, call: ir.IRExpr, indent: int) -> list[str]:
        pad = "    " * indent
        lines: list[str] = []
        cleanup: list[str] = []
        args: list[str] = []

        if isinstance(call, ir.IRIndirectCall):
            assert isinstance(call.callee.typ, FunctionType)
            function_type = call.callee.typ
            callee = self.emit_expr(call.callee)
            lines.extend(pad + line for line in callee.prelude)
            callee_name = self.temp("defer_callee")
            callee_initializer = self.take_or_retain(callee, function_type)
            lines.append(f"{pad}{self.c_type(function_type)} {callee_name} = {callee_initializer};")
            cleanup.append(
                f"if (zl_fn_is_none({callee_name})) zy2_panic_at({self.c_string(call.span.source_name)}, "
                f"{call.span.line}, {call.span.column}, \"attempted to call an empty function value\");"
            )
            cleanup.append(
                f"if (!zl_fn_matches({callee_name}, {self.c_string(function_type.display())})) "
                f"zy2_panic_at({self.c_string(call.span.source_name)}, {call.span.line}, "
                f"{call.span.column}, \"function value signature mismatch\");"
            )
            target = f"ZL_FN_CALL_AS({self.type_name(function_type)}_call, {callee_name})"
            values = call.args
            args.append(f"{callee_name}.env")
            releases: list[str] = [self.release_stmt(callee_name, function_type)]
        elif isinstance(call, ir.IRCall):
            target = call.target
            values = call.args
            releases = []
        else:
            raise ValueError("verified defer is not callable")

        for argument in values:
            value = self.emit_expr(argument)
            lines.extend(pad + line for line in value.prelude)
            temp = self.temp("defer_argument")
            initializer = self.take_or_retain(value, argument.typ)
            lines.append(f"{pad}{self.c_type(argument.typ)} {temp} = {initializer};")
            args.append(temp)
            if self.is_managed(argument.typ):
                releases.append(self.release_stmt(temp, argument.typ))

        cleanup.append(f"(void){target}({', '.join(args)});")
        cleanup.extend(reversed(releases))
        self.deferred_scopes[-1].append(cleanup)
        return lines

    @staticmethod
    def control_condition(code: str) -> str:
        value = code.strip()
        if value.startswith("(") and value.endswith(")"):
            depth = 0
            for index, char in enumerate(value):
                if char == "(":
                    depth += 1
                elif char == ")":
                    depth -= 1
                    if depth == 0 and index != len(value) - 1:
                        break
            else:
                if depth == 0:
                    return value
        return f"({value})"

    def emit_expr(self, expression: ir.IRExpr) -> CExpr:
        if isinstance(expression, ir.IRInt):
            if is_unsigned_integer(expression.typ):
                return CExpr(f"UINT64_C({expression.value})", [])
            return CExpr(str(expression.value), [])
        if isinstance(expression, ir.IRFloat):
            suffix = "f" if expression.typ == PrimitiveType("f32") else ""
            return CExpr(f"{expression.value}{suffix}", [])
        if isinstance(expression, ir.IRString):
            return CExpr(f"zl_string_borrow({self.c_string(expression.value)})", [])
        if isinstance(expression, ir.IRFString):
            return self.emit_fstring(expression)
        if isinstance(expression, ir.IRBool):
            return CExpr("true" if expression.value else "false", [])
        if isinstance(expression, ir.IRStaticTypeTest):
            raise ValueError("unresolved generic TYPEOF__ test reached C generation")
        if isinstance(expression, ir.IRNull):
            return CExpr(f"({self.c_type(expression.typ)}){{ .has_value = false }}", [])
        if isinstance(expression, ir.IROptionalSome):
            value = self.emit_expr(expression.value)
            initializer = self.take_or_retain(value, expression.value.typ)
            return CExpr(
                f"({self.c_type(expression.typ)}){{ .has_value = true, .value = {initializer} }}",
                value.prelude,
                owned=self.is_managed(expression.typ),
            )
        if isinstance(expression, ir.IROptionalValue):
            optional = self.emit_expr(expression.optional)
            if not self.is_managed(expression.typ):
                return CExpr(f"({optional.code}).value", optional.prelude)
            optional_temp = self.temp("optional_value_source")
            result = self.temp("optional_value")
            prelude = list(optional.prelude)
            prelude.append(f"{self.c_type(expression.optional.typ)} {optional_temp} = {optional.code};")
            prelude.append(
                f"{self.c_type(expression.typ)} {result} = {self.retain_expr(f'{optional_temp}.value', expression.typ)};"
            )
            if optional.owned:
                prelude.append(self.release_stmt(optional_temp, expression.optional.typ))
            return CExpr(result, prelude, owned=True)
        if isinstance(expression, ir.IRName):
            return CExpr(self.ident(expression.name), [])
        if isinstance(expression, ir.IRCapture):
            if self.current_closure is None:
                raise ValueError("closure capture reached C generation outside a closure")
            return CExpr(f"__zy_env->{self.ident(expression.name)}", [])
        if isinstance(expression, ir.IRBorrow):
            value = self.emit_place(expression.value)
            return CExpr(
                f"({self.c_type(expression.typ)}){{ .data = &({value.code}), .pin = NULL }}",
                value.prelude,
                owned=True,
            )
        if isinstance(expression, ir.IRReferencePlace):
            reference = self.emit_expr(expression.reference)
            if reference.owned:
                raise ValueError("reference receiver must be stored in a stable local before use")
            return CExpr(f"*(({reference.code}).data)", reference.prelude)
        if isinstance(expression, ir.IRReferenceCoerce):
            reference = self.emit_expr(expression.reference)
            return CExpr(
                f"({self.c_type(expression.typ)}){{ .data = ({reference.code}).data, .pin = ({reference.code}).pin }}",
                reference.prelude,
                owned=reference.owned,
            )
        if isinstance(expression, ir.IRReferenceValue):
            reference = self.emit_expr(expression.reference)
            prelude = list(reference.prelude)
            reference_code = reference.code
            if reference.owned:
                reference_temp = self.temp("reference")
                prelude.append(f"{self.c_type(expression.reference.typ)} {reference_temp} = {reference.code};")
                reference_code = reference_temp
            pointee = f"*(({reference_code}).data)"
            if self.is_managed(expression.typ):
                result = self.temp("referenced_value")
                prelude.append(
                    f"{self.c_type(expression.typ)} {result} = {self.retain_expr(pointee, expression.typ)};"
                )
                if reference.owned:
                    prelude.append(self.release_stmt(reference_code, expression.reference.typ))
                return CExpr(result, prelude, owned=True)
            if reference.owned:
                result = self.temp("referenced_value")
                prelude.append(f"{self.c_type(expression.typ)} {result} = {pointee};")
                prelude.append(self.release_stmt(reference_code, expression.reference.typ))
                return CExpr(result, prelude)
            return CExpr(pointee, prelude)
        if isinstance(expression, ir.IRUnary):
            operand = self.emit_expr(expression.operand)
            return CExpr(f"({expression.operator}{operand.code})", operand.prelude)
        if isinstance(expression, ir.IRBinary):
            return self.emit_binary(expression)
        if isinstance(expression, ir.IRCast):
            return self.emit_cast(expression)
        if isinstance(expression, ir.IRField):
            receiver = self.emit_expr(expression.receiver)
            if expression.receiver.typ in self.classes:
                if receiver.owned:
                    receiver_temp = self.temp("class_receiver")
                    result_temp = self.temp("class_field")
                    prelude = list(receiver.prelude)
                    prelude.append(f"{self.c_type(expression.receiver.typ)} {receiver_temp} = {receiver.code};")
                    field_code = f"({receiver_temp}).data->{self.ident(expression.name)}"
                    prelude.append(
                        f"{self.c_type(expression.typ)} {result_temp} = {self.retain_expr(field_code, expression.typ)};"
                    )
                    prelude.append(self.release_stmt(receiver_temp, expression.receiver.typ))
                    return CExpr(result_temp, prelude, owned=self.is_managed(expression.typ))
                return CExpr(f"({receiver.code}).data->{self.ident(expression.name)}", receiver.prelude)
            if receiver.owned:
                receiver_temp = self.temp("field_receiver")
                result_temp = self.temp("field_value")
                prelude = list(receiver.prelude)
                prelude.append(
                    f"{self.c_type(expression.receiver.typ)} {receiver_temp} = {receiver.code};"
                )
                field_code = f"({receiver_temp}).{self.ident(expression.name)}"
                field_value = self.retain_expr(field_code, expression.typ)
                prelude.append(f"{self.c_type(expression.typ)} {result_temp} = {field_value};")
                prelude.append(self.release_stmt(receiver_temp, expression.receiver.typ))
                return CExpr(result_temp, prelude, owned=self.is_managed(expression.typ))
            return CExpr(f"({receiver.code}).{self.ident(expression.name)}", receiver.prelude)
        if isinstance(expression, ir.IRFunctionRef):
            assert isinstance(expression.typ, FunctionType)
            adapter = self.function_refs[(expression.target, expression.typ)]
            signature = self.c_string(expression.typ.display())
            return CExpr(
                f"({self.c_type(expression.typ)}){{ .call = (ZL_GenericCall){adapter}, .env = NULL, .owner = NULL, .signature = {signature} }}",
                [],
            )
        if isinstance(expression, ir.IRClosure):
            closure = next(
                (item for item in self.program.closures if item.name == expression.target),
                None,
            ) if self.program is not None else None
            if closure is None:
                raise ValueError(f"missing closure definition `{expression.target}`")
            env_type = self.closure_env_name(closure)
            env_name = self.temp("closure_env")
            result = self.temp("closure")
            prelude: list[str] = []
            if expression.captures:
                prelude.append(f"{env_type}* {env_name} = ({env_type}*)calloc(1u, sizeof({env_type}));")
                prelude.append(f"if (!{env_name}) zy2_arc_panic(\"cannot allocate closure environment\");")
                capture_types = dict(closure.captures)
                for name, capture in expression.captures:
                    value = self.emit_expr(capture)
                    prelude.extend(value.prelude)
                    typ = capture_types[name]
                    prelude.append(
                        f"{env_name}->{self.ident(name)} = {self.take_or_retain(value, typ)};"
                    )
                owner = f"zy2_arc_new({env_name}, {self.closure_drop_name(closure)})"
                env_value = env_name
            else:
                owner = "NULL"
                env_value = "NULL"
            prelude.append(
                f"{self.c_type(expression.typ)} {result} = "
                f"({self.c_type(expression.typ)}){{ .call = (ZL_GenericCall){expression.target}, "
                f".env = {env_value}, .owner = {owner}, .signature = {self.c_string(expression.typ.display())} }};"
            )
            return CExpr(result, prelude, owned=True)
        if isinstance(expression, ir.IRIndirectCall):
            return self.emit_indirect_call(expression)
        if isinstance(expression, ir.IRCall):
            return self.emit_call(expression, propagate=True)
        if isinstance(expression, ir.IRTuple):
            return self.emit_aggregate(expression.typ, expression.items, [f"item_{i}" for i in range(len(expression.items))])
        if isinstance(expression, ir.IRList):
            return self.emit_list(expression)
        if isinstance(expression, ir.IRStruct):
            values = tuple(value for _, value in expression.fields)
            names = [self.ident(name) for name, _ in expression.fields]
            return self.emit_aggregate(expression.typ, values, names)
        if isinstance(expression, ir.IRClassNew):
            return self.emit_class_new(expression)
        if isinstance(expression, ir.IRStructMetadata):
            return self.emit_struct_metadata(expression)
        if isinstance(expression, ir.IRErrorStack):
            error = self.emit_expr(expression.error)
            error_temp = self.temp("error_stack_source")
            result = self.temp("error_stack")
            index = self.temp("error_frame_index")
            frame = self.temp("error_frame")
            list_name = self.type_name(expression.typ)
            prelude = list(error.prelude)
            prelude.extend(
                [
                    f"zy2_Error {error_temp} = {error.code};",
                    f"{list_name} {result} = {list_name}_new({error_temp}.frame_count);",
                    f"for (uint32_t {index} = 0u; {index} < {error_temp}.frame_count; ++{index}) {{",
                    f"    ZL_String {frame} = zy2_error_frame_format({error_temp}.frames[{index}]);",
                    f"    {list_name}_push_copy(&{result}, {frame});",
                    f"    zl_string_release({frame});",
                    "}",
                ]
            )
            if error.owned:
                prelude.append(self.release_stmt(error_temp, ERROR))
            return CExpr(result, prelude, owned=True)
        if isinstance(expression, ir.IRBox):
            value = self.emit_expr(expression.value)
            return CExpr(
                f"{self.type_name(expression.typ)}_new({self.take_or_retain(value, expression.value.typ)})",
                value.prelude,
                owned=True,
            )
        if isinstance(expression, ir.IRBoxValue):
            box = self.emit_expr(expression.box)
            if box.owned:
                box_temp = self.temp("box")
                value_temp = self.temp("box_value")
                prelude = list(box.prelude)
                prelude.append(f"{self.c_type(expression.box.typ)} {box_temp} = {box.code};")
                prelude.append(
                    f"{self.c_type(expression.typ)} {value_temp} = {self.retain_expr(f'*{box_temp}.data', expression.typ)};"
                )
                prelude.append(self.release_stmt(box_temp, expression.box.typ))
                return CExpr(value_temp, prelude, owned=self.is_managed(expression.typ))
            value_code = f"*({box.code}).data"
            if self.is_managed(expression.typ):
                value_temp = self.temp("box_value")
                prelude = list(box.prelude)
                prelude.append(
                    f"{self.c_type(expression.typ)} {value_temp} = {self.retain_expr(value_code, expression.typ)};"
                )
                return CExpr(value_temp, prelude, owned=True)
            return CExpr(value_code, box.prelude)
        if isinstance(expression, ir.IRArcCount):
            value = self.emit_expr(expression.value)
            if value.owned:
                box_temp = self.temp("box")
                count_temp = self.temp("arc_count")
                prelude = list(value.prelude)
                prelude.append(f"{self.c_type(expression.value.typ)} {box_temp} = {value.code};")
                prelude.append(f"uintptr_t {count_temp} = (uintptr_t)zy2_arc_strong_count({box_temp}.owner);")
                prelude.append(self.release_stmt(box_temp, expression.value.typ))
                return CExpr(count_temp, prelude)
            return CExpr(f"zy2_arc_strong_count(({value.code}).owner)", value.prelude)
        if isinstance(expression, ir.IRCatch):
            return self.emit_catch(expression)
        if isinstance(expression, ir.IRSpawn):
            result_type = expression.call.typ
            result_size = "0" if result_type == VOID else f"sizeof({self.c_type(result_type)})"
            return CExpr(
                f"({self.c_type(expression.typ)}){{ .control = zy2_task_spawn(__zy2_spawn_{expression.spawn_id}, NULL, {result_size}) }}",
                [],
            )
        if isinstance(expression, ir.IRAwait):
            task = self.emit_expr(expression.task)
            prelude = list(task.prelude)
            if expression.typ == VOID:
                prelude.append(f"zy2_task_await_and_destroy(&({task.code}).control, NULL, 0);")
                return CExpr("((void)0)", prelude)
            result = self.temp("await")
            prelude.append(f"{self.c_type(expression.typ)} {result};")
            prelude.append(
                f"zy2_task_await_and_destroy(&({task.code}).control, &{result}, sizeof({result}));"
            )
            return CExpr(result, prelude)
        raise ValueError(f"unsupported IR expression {type(expression).__name__}")

    def emit_struct_metadata_tables(self) -> list[str]:
        lines: list[str] = []
        for struct_name, category in sorted(self.metadata_uses):
            items = self.struct_metadata_items(struct_name, category)
            if not items:
                continue
            values = ", ".join(
                f"{{ .data = {self.c_string(item)}, .byte_len = {len(item.encode('utf-8'))}u, .owner = NULL }}"
                for item in items
            )
            lines.append(f"static ZL_String {self.struct_metadata_name(struct_name, category)}[] = {{ {values} }};")
        return lines

    def emit_struct_metadata(self, expression: ir.IRStructMetadata) -> CExpr:
        receiver = self.emit_expr(expression.receiver)
        prelude = list(receiver.prelude)
        if receiver.owned:
            receiver_temp = self.temp("metadata_receiver")
            prelude.append(f"{self.c_type(expression.receiver.typ)} {receiver_temp} = {receiver.code};")
            prelude.append(self.release_stmt(receiver_temp, expression.receiver.typ))
        else:
            prelude.append(f"(void)({receiver.code});")
        items = self.struct_metadata_items(expression.struct_name, expression.category)
        if not items:
            return CExpr(f"{self.type_name(expression.typ)}_borrow(NULL, 0)", prelude)
        name = self.struct_metadata_name(expression.struct_name, expression.category)
        return CExpr(
            f"{self.type_name(expression.typ)}_borrow({name}, {len(items)})",
            prelude,
        )

    def struct_metadata_items(self, struct_name: str, category: str) -> tuple[str, ...]:
        if category == "attributes":
            return tuple(field.name for field in self.structs[struct_name].fields)
        assert self.program is not None
        return tuple(
            function.name
            for function in self.program.functions
            if isinstance(function.receiver_type, NamedType) and function.receiver_type.name == struct_name
        )

    def struct_metadata_name(self, struct_name: str, category: str) -> str:
        return f"zy2_meta_{self.ident(struct_name)}_{category}"

    def emit_cast(self, expression: ir.IRCast) -> CExpr:
        value = self.emit_expr(expression.value)
        if expression.typ == expression.value.typ:
            return value
        if expression.typ == STR and expression.value.typ == BOOL:
            return CExpr(
                f"(({value.code}) ? zl_string_borrow(\"true\") : zl_string_borrow(\"false\"))",
                value.prelude,
            )
        if (
            expression.typ == STR
            and isinstance(expression.value.typ, OptionalType)
            and expression.value.typ.inner == STR
        ):
            optional_value = self.temp("optional_text")
            result = self.temp("optional_text_result")
            prelude = list(value.prelude)
            prelude.append(f"{self.c_type(expression.value.typ)} {optional_value} = {value.code};")
            prelude.append(
                f"ZL_String {result} = {optional_value}.has_value "
                f"? zl_string_retain({optional_value}.value) : zl_string_borrow(\"null\");"
            )
            if value.owned:
                prelude.append(self.release_stmt(optional_value, expression.value.typ))
            return CExpr(result, prelude, owned=True)
        if expression.typ == STR and is_numeric(expression.value.typ):
            buffer = self.temp("number_text")
            prelude = list(value.prelude)
            prelude.append(f"char {buffer}[64];")
            if is_float(expression.value.typ):
                precision = "9" if expression.value.typ == PrimitiveType("f32") else "17"
                prelude.append(
                    f"snprintf({buffer}, sizeof({buffer}), \"%.{precision}g\", (double)({value.code}));"
                )
            elif is_signed_integer(expression.value.typ):
                prelude.append(
                    f"snprintf({buffer}, sizeof({buffer}), \"%lld\", (long long)({value.code}));"
                )
            else:
                prelude.append(
                    f"snprintf({buffer}, sizeof({buffer}), \"%llu\", (unsigned long long)({value.code}));"
                )
            result = self.temp("number_string")
            prelude.append(f"ZL_String {result} = zl_string_copy({buffer});")
            return CExpr(result, prelude, owned=True)
        if expression.typ == BOOL and is_numeric(expression.value.typ):
            return CExpr(f"(({value.code}) != 0)", value.prelude)
        return CExpr(f"(({self.c_type(expression.typ)})({value.code}))", value.prelude)

    def emit_fstring(self, expression: ir.IRFString) -> CExpr:
        result = self.temp("fstring")
        prelude = [f"char* {result} = zy2_format_begin();"]
        for item in expression.parts:
            if isinstance(item, str):
                if item:
                    prelude.append(f"zy2_format_append({result}, {self.c_string(item)});")
                continue
            value = self.emit_expr(item)
            prelude.extend(value.prelude)
            if item.typ == STR:
                text = self.temp("fstring_text")
                prelude.append(f"ZL_String {text} = {value.code};")
                prelude.append(f"zy2_format_append({result}, zl_string_data({text}));")
                if value.owned:
                    prelude.append(self.release_stmt(text, STR))
            elif item.typ == BOOL:
                prelude.append(f"zy2_format_append_bool({result}, {value.code});")
            elif is_float(item.typ):
                precision = 9 if item.typ == PrimitiveType("f32") else 17
                prelude.append(f"zy2_format_append_f64({result}, (double)({value.code}), {precision});")
            elif is_signed_integer(item.typ):
                prelude.append(f"zy2_format_append_i64({result}, (int64_t)({value.code}));")
            elif is_unsigned_integer(item.typ):
                prelude.append(f"zy2_format_append_u64({result}, (uint64_t)({value.code}));")
            elif isinstance(item.typ, OptionalType) and item.typ.inner == STR:
                optional = self.temp("fstring_optional")
                prelude.append(f"{self.c_type(item.typ)} {optional} = {value.code};")
                prelude.append(
                    f"zy2_format_append({result}, {optional}.has_value ? zl_string_data({optional}.value) : \"null\");"
                )
                if value.owned:
                    prelude.append(self.release_stmt(optional, item.typ))
            else:
                raise ValueError(f"unsupported f-string IR type `{item.typ.display()}`")
        owned = self.temp("fstring_string")
        prelude.append(f"ZL_String {owned} = zl_string_copy({result});")
        return CExpr(owned, prelude, owned=True)

    def emit_binary(self, expression: ir.IRBinary) -> CExpr:
        if expression.operator in {"==", "!="} and (
            isinstance(expression.left, ir.IRNull) or isinstance(expression.right, ir.IRNull)
        ):
            other = expression.right if isinstance(expression.left, ir.IRNull) else expression.left
            value = self.emit_expr(other)
            test = value.code + ".has_value"
            if expression.operator == "==":
                test = "!" + test
            return CExpr(f"({test})", value.prelude)
        left = self.emit_expr(expression.left)
        right = self.emit_expr(expression.right)
        prelude = left.prelude + right.prelude
        if (is_box(expression.left.typ) or expression.left.typ in self.classes) and expression.operator in {"==", "!="}:
            left_code = left.code
            right_code = right.code
            if left.owned:
                left_code = self.temp("box_left")
                prelude.append(f"{self.c_type(expression.left.typ)} {left_code} = {left.code};")
            if right.owned:
                right_code = self.temp("box_right")
                prelude.append(f"{self.c_type(expression.right.typ)} {right_code} = {right.code};")
            result = self.temp("box_compare")
            comparison = f"({left_code}).owner == ({right_code}).owner"
            if expression.operator == "!=":
                comparison = f"!({comparison})"
            prelude.append(f"bool {result} = ({comparison});")
            if left.owned:
                prelude.append(self.release_stmt(left_code, expression.left.typ))
            if right.owned:
                prelude.append(self.release_stmt(right_code, expression.right.typ))
            return CExpr(result, prelude)
        if expression.left.typ == STR and expression.operator in {"==", "!="}:
            return self.emit_structural_equality(expression, left, right)
        if expression.operator in {"==", "!="} and self.is_structural_equality_type(expression.left.typ):
            return self.emit_structural_equality(expression, left, right)
        if (
            expression.operator in {"<", "<=", ">", ">=", "==", "!="}
            and is_numeric(expression.left.typ)
            and is_numeric(expression.right.typ)
            and expression.left.typ != expression.right.typ
        ):
            return self.emit_mixed_numeric_comparison(expression, left, right)
        return CExpr(f"({left.code} {expression.operator} {right.code})", prelude)

    def is_structural_equality_type(self, typ: Type) -> bool:
        return (
            isinstance(typ, OptionalType)
            or isinstance(typ, TupleType)
            or (isinstance(typ, NamedType) and typ.name in self.structs)
        )

    def emit_structural_equality(self, expression: ir.IRBinary, left: CExpr, right: CExpr) -> CExpr:
        left_temp = self.temp("equal_left")
        right_temp = self.temp("equal_right")
        prelude = list(left.prelude)
        prelude.append(f"{self.c_type(expression.left.typ)} {left_temp} = {left.code};")
        prelude.extend(right.prelude)
        prelude.append(f"{self.c_type(expression.right.typ)} {right_temp} = {right.code};")
        comparison = self.equality_code(expression.left.typ, left_temp, right_temp)
        if expression.operator == "!=":
            comparison = f"!({comparison})"
        if left.owned or right.owned:
            result = self.temp("equal")
            prelude.append(f"bool {result} = ({comparison});")
            if left.owned:
                prelude.append(self.release_stmt(left_temp, expression.left.typ))
            if right.owned:
                prelude.append(self.release_stmt(right_temp, expression.right.typ))
            return CExpr(result, prelude)
        return CExpr(f"({comparison})", prelude)

    def equality_code(self, typ: Type, left: str, right: str) -> str:
        if typ == STR:
            return f"zl_string_equal(({left}), ({right}))"
        if typ == BOOL or is_numeric(typ):
            return f"(({left}) == ({right}))"
        if isinstance(typ, FunctionType):
            return f"zl_fn_equal(({left}), ({right}))"
        if is_box(typ):
            return f"(({left}).owner == ({right}).owner)"
        if isinstance(typ, OptionalType):
            values_equal = self.equality_code(typ.inner, f"({left}).value", f"({right}).value")
            return (
                f"((!({left}).has_value && !({right}).has_value) || "
                f"(({left}).has_value && ({right}).has_value && ({values_equal})))"
            )
        if isinstance(typ, TupleType):
            comparisons = [
                self.equality_code(item, f"({left}).item_{index}", f"({right}).item_{index}")
                for index, item in enumerate(typ.items)
            ]
            return "(" + " && ".join(comparisons) + ")" if comparisons else "true"
        if isinstance(typ, NamedType) and typ.name in self.structs:
            comparisons = [
                self.equality_code(
                    field.typ,
                    f"({left}).{self.ident(field.name)}",
                    f"({right}).{self.ident(field.name)}",
                )
                for field in self.structs[typ.name].fields
            ]
            return "(" + " && ".join(comparisons) + ")" if comparisons else "true"
        raise ValueError(f"type `{typ.display()}` has no equality code")

    def emit_mixed_numeric_comparison(self, expression: ir.IRBinary, left: CExpr, right: CExpr) -> CExpr:
        left_temp = self.temp("compare_left")
        right_temp = self.temp("compare_right")
        prelude = list(left.prelude)
        prelude.append(f"{self.c_type(expression.left.typ)} {left_temp} = {left.code};")
        prelude.extend(right.prelude)
        prelude.append(f"{self.c_type(expression.right.typ)} {right_temp} = {right.code};")

        if is_integer(expression.left.typ) and is_integer(expression.right.typ):
            left_signed = is_signed_integer(expression.left.typ)
            right_signed = is_signed_integer(expression.right.typ)
            if left_signed != right_signed:
                operator_names = {
                    "==": "eq",
                    "!=": "ne",
                    "<": "lt",
                    "<=": "le",
                    ">": "gt",
                    ">=": "ge",
                }
                operator = expression.operator
                if left_signed:
                    signed_value = left_temp
                    unsigned_value = right_temp
                else:
                    signed_value = right_temp
                    unsigned_value = left_temp
                    operator = {"<": ">", "<=": ">=", ">": "<", ">=": "<="}.get(operator, operator)
                helper = f"zy2_compare_i64_u64_{operator_names[operator]}"
                return CExpr(
                    f"{helper}((int64_t)({signed_value}), (uint64_t)({unsigned_value}))",
                    prelude,
                )
            common = "int64_t" if left_signed else "uint64_t"
            return CExpr(
                f"(({common})({left_temp}) {expression.operator} ({common})({right_temp}))",
                prelude,
            )

        return CExpr(
            f"((double)({left_temp}) {expression.operator} (double)({right_temp}))",
            prelude,
        )

    def emit_call(self, expression: ir.IRCall, *, propagate: bool) -> CExpr:
        args: list[str] = []
        prelude: list[str] = []
        owned_arg_releases: list[str] = []
        for arg in expression.args:
            value = self.emit_expr(arg)
            prelude.extend(value.prelude)
            if self.is_managed(arg.typ) and value.owned:
                temp = self.temp("argument")
                prelude.append(f"{self.c_type(arg.typ)} {temp} = {value.code};")
                args.append(temp)
                owned_arg_releases.append(self.release_stmt(temp, arg.typ))
            else:
                args.append(value.code)
        if expression.target == "__zy2_ref_set":
            reference_type = expression.args[0].typ
            if not isinstance(reference_type, ReferenceType):
                raise ValueError("verified REF_SET__ is missing a reference type")
            inner = reference_type.inner
            if self.is_managed(inner):
                replacement = self.temp("reference_value")
                prelude.append(f"{self.c_type(inner)} {replacement} = {self.retain_expr(args[1], inner)};")
                prelude.append(self.release_stmt(f"*(({args[0]}).data)", inner))
                prelude.append(f"*(({args[0]}).data) = {replacement};")
            else:
                prelude.append(f"*(({args[0]}).data) = {args[1]};")
            prelude.extend(owned_arg_releases)
            return CExpr("((void)0)", prelude)
        if expression.target == "__zy2_get_args":
            list_name = self.type_name(expression.typ)
            result = self.temp("process_args")
            index = self.temp("arg_index")
            prelude.append(
                f"{list_name} {result} = {list_name}_new((uintptr_t)(zy2_process_argc > 1 ? zy2_process_argc - 1 : 0));"
            )
            prelude.append(f"for (int {index} = 1; {index} < zy2_process_argc; ++{index}) {{")
            prelude.append(
                f"    {list_name}_push_copy(&{result}, zl_string_borrow(zy2_process_argv[{index}]));"
            )
            prelude.append("}")
            return CExpr(result, prelude, owned=True)
        if expression.target == "__zy2_get_exe":
            return CExpr(
                "zl_string_borrow(zy2_process_argc > 0 ? zy2_process_argv[0] : \"\")",
                prelude,
            )
        if expression.target == "zy2_list_len":
            result_value = self.temp("list_len")
            prelude.append(f"uintptr_t {result_value} = {self.type_name(expression.args[0].typ)}_len({args[0]});")
            prelude.extend(owned_arg_releases)
            return CExpr(result_value, prelude)
        if expression.target == "zy2_list_capacity":
            result_value = self.temp("list_capacity")
            list_name = self.type_name(expression.args[0].typ)
            prelude.append(
                f"uintptr_t {result_value} = ({args[0]}).storage ? ({args[0]}).storage->capacity : ({args[0]}).borrowed_len;"
            )
            prelude.extend(owned_arg_releases)
            return CExpr(result_value, prelude)
        if expression.target == "zy2_list_is_empty":
            result_value = self.temp("list_empty")
            prelude.append(f"bool {result_value} = {self.type_name(expression.args[0].typ)}_len({args[0]}) == 0;")
            prelude.extend(owned_arg_releases)
            return CExpr(result_value, prelude)
        if expression.target == "__zy2_str_to_list":
            result_value = self.temp("string_list")
            prelude.append(f"{self.c_type(expression.typ)} {result_value} = {self.type_name(expression.typ)}_from_utf8({args[0]});")
            prelude.extend(owned_arg_releases)
            return CExpr(result_value, prelude, owned=True)
        if expression.target == "__zy3_str_len":
            result_value = self.temp("string_len")
            prelude.append(f"uintptr_t {result_value} = (uintptr_t)zl_string_scalar_len({args[0]});")
            prelude.extend(owned_arg_releases)
            return CExpr(result_value, prelude)
        if expression.target == "__zy3_str_byte_len":
            result_value = self.temp("string_byte_len")
            prelude.append(f"uintptr_t {result_value} = (uintptr_t)zl_string_byte_len({args[0]});")
            prelude.extend(owned_arg_releases)
            return CExpr(result_value, prelude)
        if expression.target == "__zy3_str_get":
            result = self.temp("result")
            source_name = f"zl_string_borrow({self.c_string(expression.span.source_name)})"
            prelude.extend(
                [
                    f"{self.result_type(STR)} {result} = {{0}};",
                    f"if (!zl_string_scalar_get({args[0]}, (size_t){args[1]}, &{result}.value)) {{",
                    f"    {result}.ok = false;",
                    f"    {result}.error = (zy2_Error){{ .message = zl_string_borrow(\"str scalar index out of range\"), .source_file = {source_name}, .line = {expression.span.line}, .column = {expression.span.column} }};",
                    "} else {",
                    f"    {result}.ok = true;",
                    "}",
                ]
            )
            prelude.extend(owned_arg_releases)
            return self.finish_throwing_result(expression, result, prelude, propagate)
        if expression.target == "__zy3_str_slice":
            result = self.temp("result")
            source_name = f"zl_string_borrow({self.c_string(expression.span.source_name)})"
            prelude.extend(
                [
                    f"{self.result_type(STR)} {result} = {{0}};",
                    f"if (!zl_string_scalar_slice({args[0]}, (size_t){args[1]}, (size_t){args[2]}, &{result}.value)) {{",
                    f"    {result}.ok = false;",
                    f"    {result}.error = (zy2_Error){{ .message = zl_string_borrow(\"invalid str scalar slice\"), .source_file = {source_name}, .line = {expression.span.line}, .column = {expression.span.column} }};",
                    "} else {",
                    f"    {result}.ok = true;",
                    "}",
                ]
            )
            prelude.extend(owned_arg_releases)
            return self.finish_throwing_result(expression, result, prelude, propagate)
        if expression.target in {"__zy2_list_push", "__zy2_list_clear"}:
            list_name = self.type_name(expression.args[0].typ)
            if expression.target == "__zy2_list_push":
                prelude.append(f"{list_name}_push_copy(&({args[0]}), {args[1]});")
            else:
                prelude.append(f"{list_name}_clear(&({args[0]}));")
            prelude.extend(owned_arg_releases)
            return CExpr("((void)0)", prelude)
        if expression.target == "__zy2_list_get":
            list_value = self.temp("list")
            index_value = self.temp("index")
            result = self.temp("result")
            source_name = f"zl_string_borrow({self.c_string(expression.span.source_name)})"
            list_name = self.type_name(expression.args[0].typ)
            element_type = expression.typ
            prelude.extend(
                [
                    f"{self.c_type(expression.args[0].typ)} {list_value} = {args[0]};",
                    f"int32_t {index_value} = {args[1]};",
                    f"{self.result_type(expression.typ)} {result} = {{0}};",
                    f"if ({index_value} < 0 || (uintptr_t){index_value} >= {list_name}_len({list_value})) {{",
                    f"    {result}.ok = false;",
                    f"    {result}.error = (zy2_Error){{ .message = zl_string_borrow(\"List index out of range\"), .source_file = {source_name}, .line = {expression.span.line}, .column = {expression.span.column} }};",
                    "} else {",
                    f"    {result}.ok = true;",
                    f"    {result}.value = {self.retain_expr(f'{list_name}_items({list_value})[{index_value}]', element_type)};",
                    "}",
                ]
            )
            prelude.extend(owned_arg_releases)
            return self.finish_throwing_result(expression, result, prelude, propagate)
        if expression.target in {"__zy2_list_borrow", "__zy2_list_borrow_mut"}:
            list_value = self.temp("list_borrow_source")
            index_value = self.temp("index")
            result = self.temp("result")
            source_name = f"zl_string_borrow({self.c_string(expression.span.source_name)})"
            list_type = expression.args[0].typ
            list_name = self.type_name(list_type)
            reference_type = expression.typ
            assert isinstance(reference_type, ReferenceType)
            prelude.append(f"int32_t {index_value} = {args[1]};")
            if expression.target == "__zy2_list_borrow_mut":
                prelude.append(f"{list_name}_ensure_mutable(&({args[0]}), 0);")
                list_code = args[0]
            else:
                prelude.append(f"{self.c_type(list_type)} {list_value} = {args[0]};")
                list_code = list_value
            prelude.extend(
                [
                    f"{self.result_type(reference_type)} {result} = {{0}};",
                    f"if ({index_value} < 0 || (uintptr_t){index_value} >= {list_name}_len({list_code})) {{",
                    f"    {result}.ok = false;",
                    f"    {result}.error = (zy2_Error){{ .message = zl_string_borrow(\"List index out of range\"), .source_file = {source_name}, .line = {expression.span.line}, .column = {expression.span.column} }};",
                    "} else {",
                    f"    {result}.ok = true;",
                    f"    {result}.value = ({self.c_type(reference_type)}){{ .data = &{list_name}_items({list_code})[{index_value}], .pin = ({list_code}).owner }};",
                    f"    zy2_arc_retain({result}.value.pin);",
                    "}",
                ]
            )
            prelude.extend(owned_arg_releases)
            return self.finish_throwing_result(expression, result, prelude, propagate)
        if expression.target == "__zy2_list_set":
            list_value = args[0]
            index_value = self.temp("index")
            result = self.temp("result")
            source_name = f"zl_string_borrow({self.c_string(expression.span.source_name)})"
            list_name = self.type_name(expression.args[0].typ)
            prelude.extend(
                [
                    f"int32_t {index_value} = {args[1]};",
                    f"{self.result_type(VOID)} {result} = {{0}};",
                    f"if ({index_value} < 0 || (uintptr_t){index_value} >= {list_name}_len({list_value})) {{",
                    f"    {result}.ok = false;",
                    f"    {result}.error = (zy2_Error){{ .message = zl_string_borrow(\"List index out of range\"), .source_file = {source_name}, .line = {expression.span.line}, .column = {expression.span.column} }};",
                    "} else {",
                    f"    {list_name}_set_copy(&({list_value}), (uintptr_t){index_value}, {args[2]});",
                    f"    {result}.ok = true;",
                    "}",
                ]
            )
            prelude.extend(owned_arg_releases)
            return self.finish_throwing_result(expression, result, prelude, propagate)
        if expression.target in {"__zy2_list_pop", "__zy2_list_remove"}:
            list_value = args[0]
            result = self.temp("result")
            source_name = f"zl_string_borrow({self.c_string(expression.span.source_name)})"
            list_type = expression.args[0].typ
            list_name = self.type_name(list_type)
            element_type = expression.typ
            index_value = self.temp("index")
            if expression.target == "__zy2_list_pop":
                index_setup = f"uintptr_t {index_value} = {list_name}_len({list_value}) - 1;"
                invalid = f"{list_name}_len({list_value}) == 0"
                message = "cannot pop from an empty List"
            else:
                prelude.append(f"int32_t {index_value} = {args[1]};")
                index_setup = ""
                invalid = f"{index_value} < 0 || (uintptr_t){index_value} >= {list_name}_len({list_value})"
                message = "List index out of range"
            prelude.extend(
                [
                    f"{self.result_type(element_type)} {result} = {{0}};",
                    f"if ({invalid}) {{",
                    f"    {result}.ok = false;",
                    f"    {result}.error = (zy2_Error){{ .message = zl_string_borrow({self.c_string(message)}), .source_file = {source_name}, .line = {expression.span.line}, .column = {expression.span.column} }};",
                    "} else {",
                ]
            )
            if index_setup:
                prelude.append(f"    {index_setup}")
            prelude.extend(
                [
                    f"    {list_name}_ensure_mutable(&({list_value}), 0);",
                    f"    {result}.value = ({list_value}).storage->items[{index_value}];",
                    f"    uintptr_t tail = ({list_value}).storage->len - (uintptr_t){index_value} - 1;",
                    "    if (tail > 0) {",
                    f"        memmove(&({list_value}).storage->items[{index_value}], &({list_value}).storage->items[{index_value} + 1], tail * sizeof({self.c_type(element_type)}));",
                    "    }",
                    f"    ({list_value}).storage->len -= 1;",
                    f"    ({list_value}).storage->items[({list_value}).storage->len] = {self.zero_value(element_type)};",
                    f"    {result}.ok = true;",
                    "}",
                ]
            )
            prelude.extend(owned_arg_releases)
            return self.finish_throwing_result(expression, result, prelude, propagate)
        code = f"{expression.target}({', '.join(args)})"
        if expression.throws is None:
            if owned_arg_releases:
                if expression.typ == VOID:
                    prelude.append(f"(void)({code});")
                    prelude.extend(owned_arg_releases)
                    return CExpr("((void)0)", prelude)
                result_value = self.temp("call")
                prelude.append(f"{self.c_type(expression.typ)} {result_value} = {code};")
                prelude.extend(owned_arg_releases)
                return CExpr(result_value, prelude, owned=self.is_managed(expression.typ))
            return CExpr(code, prelude, owned=self.is_managed(expression.typ))
        result = self.temp("result")
        prelude.append(f"{self.result_type(expression.typ)} {result} = {code};")
        prelude.extend(owned_arg_releases)
        return self.finish_throwing_result(expression, result, prelude, propagate)

    def emit_indirect_call(self, expression: ir.IRIndirectCall) -> CExpr:
        assert isinstance(expression.callee.typ, FunctionType)
        function_type = expression.callee.typ
        callee = self.emit_expr(expression.callee)
        callee_temp = self.temp("callback")
        prelude = list(callee.prelude)
        prelude.append(f"{self.c_type(expression.callee.typ)} {callee_temp} = {callee.code};")
        prelude.append(
            f"if (zl_fn_is_none({callee_temp})) zy2_panic_at({self.c_string(expression.span.source_name)}, "
            f"{expression.span.line}, {expression.span.column}, \"attempted to call an empty function value\");"
        )
        prelude.append(
            f"if (!zl_fn_matches({callee_temp}, {self.c_string(function_type.display())})) "
            f"zy2_panic_at({self.c_string(expression.span.source_name)}, {expression.span.line}, "
            f"{expression.span.column}, \"function value signature mismatch\");"
        )
        args: list[str] = []
        owned_arg_releases: list[str] = []
        for arg in expression.args:
            value = self.emit_expr(arg)
            prelude.extend(value.prelude)
            if self.is_managed(arg.typ) and value.owned:
                temp = self.temp("indirect_argument")
                prelude.append(f"{self.c_type(arg.typ)} {temp} = {value.code};")
                args.append(temp)
                owned_arg_releases.append(self.release_stmt(temp, arg.typ))
            else:
                args.append(value.code)
        call_args = ", ".join([f"{callee_temp}.env", *args])
        code = f"ZL_FN_CALL_AS({self.type_name(function_type)}_call, {callee_temp})({call_args})"
        call_cleanup = list(owned_arg_releases)
        if callee.owned:
            call_cleanup.append(self.release_stmt(callee_temp, function_type))
        if call_cleanup:
            if expression.typ == VOID:
                prelude.append(f"(void)({code});")
                prelude.extend(call_cleanup)
                return CExpr("((void)0)", prelude)
            result = self.temp("indirect_call")
            prelude.append(f"{self.c_type(expression.typ)} {result} = {code};")
            prelude.extend(call_cleanup)
            return CExpr(result, prelude, owned=self.is_managed(expression.typ))
        return CExpr(code, prelude, owned=self.is_managed(expression.typ))

    def finish_throwing_result(
        self,
        expression: ir.IRCall,
        result: str,
        prelude: list[str],
        propagate: bool,
    ) -> CExpr:
        if propagate:
            function_name = self.current_function.name if self.current_function else "<unknown>"
            push_frame = (
                f"zy2_error_push_frame(&{result}.error, zl_string_borrow({self.c_string(function_name)}), "
                f"zl_string_borrow({self.c_string(expression.span.source_name)}), {expression.span.line}, "
                f"{expression.span.column});"
            )
            if self.current_function and self.current_function.throws:
                current_result = self.result_type(self.current_function.return_type)
                prelude.append(f"if (!{result}.ok) {{")
                prelude.append(f"    {push_frame}")
                prelude.extend("    " + line for line in self.cleanup_lines(0, 0))
                prelude.append(f"    return ({current_result}){{ .ok = false, .error = {result}.error }};")
                prelude.append("}")
            else:
                prelude.append(f"if (!{result}.ok) {{")
                prelude.append(f"    {push_frame}")
                prelude.extend("    " + line for line in self.cleanup_lines(0, 0))
                prelude.append(f"    zy2_unhandled_error({result}.error);")
                prelude.append("}")
        result_code = "((void)0)" if expression.typ == VOID else f"{result}.value"
        return CExpr(result_code, prelude, owned=self.is_managed(expression.typ))

    def emit_catch(self, expression: ir.IRCatch) -> CExpr:
        if not isinstance(expression.value, ir.IRCall):
            raise ValueError("verified catch value is not a call")
        call = self.emit_call(expression.value, propagate=False)
        prelude = self.emit_hoisted_declarations(expression.handler, 0)
        prelude.extend(call.prelude)
        result_name = self.result_name_from_call_prelude(prelude)
        target = None
        if expression.typ != VOID:
            target = self.temp("recovered")
            prelude.append(f"{self.c_type(expression.typ)} {target} = {self.zero_value(expression.typ)};")
            prelude.append(f"if ({result_name}.ok) {{ {target} = {result_name}.value; }} else {{")
        elif expression.value.typ != VOID and self.is_managed(expression.value.typ):
            prelude.append(f"if ({result_name}.ok) {{")
            prelude.append(f"    {self.release_stmt(f'{result_name}.value', expression.value.typ)}")
            prelude.append("} else {")
        else:
            prelude.append(f"if (!{result_name}.ok) {{")
        function_name = self.current_function.name if self.current_function else "<unknown>"
        prelude.append(
            f"    zy2_error_push_frame(&{result_name}.error, zl_string_borrow({self.c_string(function_name)}), "
            f"zl_string_borrow({self.c_string(expression.span.source_name)}), {expression.span.line}, "
            f"{expression.span.column});"
        )
        prelude.append(f"    zy2_Error {self.ident(expression.error_name)} = {result_name}.error;")
        prelude.append(f"    (void){self.ident(expression.error_name)};")
        self.catch_targets.append((target, expression.typ))
        try:
            handler = self.emit_block(
                expression.handler,
                1,
                owned_params=(ir.IRParam(expression.error_name, ERROR),),
            )
        finally:
            self.catch_targets.pop()
        prelude.extend(handler)
        prelude.append("}")
        return CExpr(
            "((void)0)" if target is None else target,
            prelude,
            owned=self.is_managed(expression.typ),
        )

    @staticmethod
    def result_name_from_call_prelude(prelude: list[str]) -> str:
        for line in reversed(prelude):
            match = re.search(r"\s(__zy_result_\d+)\s*=", line)
            if match:
                return match.group(1)
        raise ValueError("throwing call did not create a result temporary")

    def emit_aggregate(self, typ: Type, values: tuple[ir.IRExpr, ...], names: list[str]) -> CExpr:
        prelude: list[str] = []
        fields: list[str] = []
        struct_fields = (
            {field.name: field.typ for field in self.structs[typ.name].fields}
            if isinstance(typ, NamedType) and typ.name in self.structs
            else {}
        )
        for name, item in zip(names, values):
            value = self.emit_expr(item)
            prelude.extend(value.prelude)
            field_type = struct_fields.get(name, item.typ)
            fields.append(f".{name} = {self.take_or_retain(value, field_type)}")
        body = ", ".join(fields)
        return CExpr(f"({self.c_type(typ)}){{ {body} }}", prelude, owned=self.is_managed(typ))

    def emit_class_new(self, expression: ir.IRClassNew) -> CExpr:
        class_def = self.classes.get(expression.typ)
        if class_def is None:
            raise ValueError(f"missing class specialization for `{expression.typ.display()}`")
        handle = self.class_c_name(expression.typ)
        payload = self.class_payload_name(expression.typ)
        result = self.temp("class")
        data = self.temp("class_data")
        prelude: list[str] = []
        args: list[str] = []
        releases: list[str] = []
        for argument in expression.args:
            value = self.emit_expr(argument)
            prelude.extend(value.prelude)
            temp = self.temp("class_argument")
            prelude.append(f"{self.c_type(argument.typ)} {temp} = {self.take_or_retain(value, argument.typ)};")
            args.append(temp)
            if self.is_managed(argument.typ):
                releases.append(self.release_stmt(temp, argument.typ))
        prelude.append(f"{payload}* {data} = ({payload}*)calloc(1u, sizeof({payload}));")
        prelude.append(f"if (!{data}) zy2_arc_panic(\"cannot allocate class `{expression.typ.display()}`\");")
        prelude.append(
            f"{handle} {result} = ({handle}){{ .data = {data}, .owner = zy2_arc_new({data}, {self.class_drop_name(expression.typ)}) }};"
        )
        field_types = {field.name: field.typ for field in class_def.fields}
        for name, default in expression.defaults:
            value = self.emit_expr(default)
            prelude.extend(value.prelude)
            field_type = field_types[name]
            prelude.append(
                f"{result}.data->{self.ident(name)} = {self.take_or_retain(value, field_type)};"
            )
        if expression.initializer:
            prelude.append(f"{expression.initializer}({', '.join([result, *args])});")
        prelude.extend(reversed(releases))
        return CExpr(result, prelude, owned=True)

    def emit_list(self, expression: ir.IRList) -> CExpr:
        element = expression.typ.args[0] if isinstance(expression.typ, NamedType) else VOID
        list_name = self.type_name(expression.typ)
        result = self.temp("list")
        prelude: list[str] = [f"{self.c_type(expression.typ)} {result} = {list_name}_new({len(expression.items)});"]
        for item in expression.items:
            value = self.emit_expr(item)
            prelude.extend(value.prelude)
            if self.is_managed(element) and value.owned:
                item_temp = self.temp("list_item")
                prelude.append(f"{self.c_type(element)} {item_temp} = {value.code};")
                prelude.append(f"{list_name}_push_copy(&{result}, {item_temp});")
                prelude.append(self.release_stmt(item_temp, element))
            else:
                prelude.append(f"{list_name}_push_copy(&{result}, {value.code});")
        return CExpr(result, prelude, owned=True)

    def result_type(self, value_type: Type) -> str:
        return self.type_name(self.result_marker(value_type))

    def c_type(self, typ: Type) -> str:
        if isinstance(typ, PrimitiveType):
            mapping = {
                "i8": "int8_t",
                "i16": "int16_t",
                "i32": "int32_t",
                "i64": "int64_t",
                "u8": "uint8_t",
                "u16": "uint16_t",
                "u32": "uint32_t",
                "u64": "uint64_t",
                "isize": "intptr_t",
                "usize": "uintptr_t",
                "f32": "float",
                "f64": "double",
                "bool": "bool",
                "str": "ZL_String",
                "void": "void",
                "Error": "zy2_Error",
            }
            return mapping[typ.name]
        if isinstance(typ, ReferenceType):
            return self.type_name(typ)
        if typ in self.classes:
            return self.class_c_name(typ)
        if isinstance(typ, NamedType) and typ.name in self.structs:
            return self.struct_c_name(typ.name)
        if isinstance(typ, FunctionType):
            return self.type_name(typ)
        return self.type_name(typ)

    def type_name(self, typ: Type) -> str:
        if isinstance(typ, OptionalType):
            return f"zy2_optional_{self.type_slug(typ.inner)}"
        if isinstance(typ, TupleType):
            return "zy2_tuple_" + "_".join(self.type_slug(item) for item in typ.items)
        if isinstance(typ, FunctionType):
            params = "_".join(self.type_slug(item) for item in typ.params) or "void"
            return f"zy2_fn_{params}_to_{self.type_slug(typ.return_type)}"
        if is_list(typ):
            return f"zy2_list_{self.type_slug(typ.args[0])}"
        if is_task(typ):
            return f"zy2_task_{self.type_slug(typ.args[0])}"
        if is_box(typ):
            return f"zy2_box_{self.type_slug(typ.args[0])}"
        if isinstance(typ, NamedType) and typ.name == "__Result":
            return f"zy2_result_{self.type_slug(typ.args[0])}"
        if isinstance(typ, ReferenceType):
            prefix = "mut_ref" if typ.mutable else "ref"
            return f"zy2_{prefix}_{self.type_slug(typ.inner)}"
        if typ in self.classes:
            return self.class_c_name(typ)
        if isinstance(typ, NamedType) and typ.name in self.structs:
            return self.struct_c_name(typ.name)
        raise ValueError(f"type `{typ.display()}` has no generated C name")

    def type_slug(self, typ: Type) -> str:
        if isinstance(typ, PrimitiveType):
            return self.ident(typ.name)
        if isinstance(typ, NamedType):
            base = self.ident(typ.name)
            return base if not typ.args else base + "_" + "_".join(self.type_slug(arg) for arg in typ.args)
        if isinstance(typ, TupleType):
            return "tuple_" + "_".join(self.type_slug(item) for item in typ.items)
        if isinstance(typ, OptionalType):
            return "optional_" + self.type_slug(typ.inner)
        if isinstance(typ, FunctionType):
            params = "_".join(self.type_slug(item) for item in typ.params) or "void"
            return f"fn_{params}_to_{self.type_slug(typ.return_type)}"
        if isinstance(typ, ReferenceType):
            prefix = "mut_ref" if typ.mutable else "ref"
            return f"{prefix}_{self.type_slug(typ.inner)}"
        raise ValueError(f"cannot create type slug for `{typ.display()}`")

    def zero_value(self, typ: Type) -> str:
        if typ == STR:
            return "(ZL_String){0}"
        if typ == ERROR:
            return "(zy2_Error){0}"
        if typ == BOOL:
            return "false"
        if isinstance(typ, FunctionType):
            return f"({self.c_type(typ)}){{0}}"
        if isinstance(typ, ReferenceType):
            return f"({self.c_type(typ)}){{0}}"
        if typ in self.classes:
            return f"({self.c_type(typ)}){{0}}"
        if isinstance(typ, PrimitiveType):
            return "0"
        return f"({self.c_type(typ)}){{0}}"

    def is_managed(self, typ: Type, visiting: set[str] | None = None) -> bool:
        if typ in {STR, ERROR} or is_box(typ) or is_list(typ) or isinstance(typ, (FunctionType, ReferenceType)):
            return True
        if typ in self.classes:
            return True
        if isinstance(typ, OptionalType):
            return self.is_managed(typ.inner, visiting)
        if isinstance(typ, TupleType):
            return any(self.is_managed(item, visiting) for item in typ.items)
        if isinstance(typ, NamedType) and typ.name in self.structs:
            visiting = set() if visiting is None else set(visiting)
            if typ.name in visiting:
                return False
            visiting.add(typ.name)
            return any(self.is_managed(field.typ, visiting) for field in self.structs[typ.name].fields)
        return False

    def retain_expr(self, code: str, typ: Type) -> str:
        if typ == STR:
            return f"zl_string_retain({code})"
        if typ == ERROR:
            return f"zy2_error_retain({code})"
        if typ in self.classes:
            return f"{self.class_c_name(typ)}_retain({code})"
        if is_box(typ):
            return f"{self.type_name(typ)}_retain({code})"
        if is_list(typ):
            return f"{self.type_name(typ)}_retain({code})"
        if isinstance(typ, FunctionType):
            return f"zl_fn_retain({code})"
        if isinstance(typ, ReferenceType):
            return f"{self.type_name(typ)}_retain({code})"
        if isinstance(typ, (OptionalType, TupleType)) and self.is_managed(typ):
            return f"{self.type_name(typ)}_retain({code})"
        if isinstance(typ, NamedType) and typ.name in self.structs and self.is_managed(typ):
            return f"{self.type_name(typ)}_retain({code})"
        return code

    def release_stmt(self, code: str, typ: Type) -> str:
        if typ == STR:
            return f"zl_string_release({code});"
        if typ == ERROR:
            return f"zy2_error_release({code});"
        if typ in self.classes:
            return f"{self.class_c_name(typ)}_release({code});"
        if is_box(typ):
            return f"{self.type_name(typ)}_release({code});"
        if is_list(typ):
            return f"{self.type_name(typ)}_release({code});"
        if isinstance(typ, FunctionType):
            return f"zl_fn_release({code});"
        if isinstance(typ, ReferenceType):
            return f"{self.type_name(typ)}_release({code});"
        if isinstance(typ, (OptionalType, TupleType)) and self.is_managed(typ):
            return f"{self.type_name(typ)}_release({code});"
        if isinstance(typ, NamedType) and typ.name in self.structs and self.is_managed(typ):
            return f"{self.type_name(typ)}_release({code});"
        return f"(void)({code});"

    def take_or_retain(self, value: CExpr, typ: Type) -> str:
        if not self.is_managed(typ) or value.owned:
            return value.code
        return self.retain_expr(value.code, typ)

    def emit_place(self, expression: ir.IRExpr) -> CExpr:
        if isinstance(expression, ir.IRName):
            return CExpr(self.ident(expression.name), [])
        if isinstance(expression, ir.IRField):
            receiver = self.emit_place(expression.receiver)
            if expression.receiver.typ in self.classes:
                return CExpr(
                    f"({receiver.code}).data->{self.ident(expression.name)}",
                    receiver.prelude,
                )
            return CExpr(f"({receiver.code}).{self.ident(expression.name)}", receiver.prelude)
        raise ValueError(f"verified borrow does not contain a stable place: {type(expression).__name__}")

    def cleanup_lines(self, start: int, indent: int) -> list[str]:
        pad = "    " * indent
        lines: list[str] = []
        for scope in reversed(self.deferred_scopes[start:]):
            for deferred in reversed(scope):
                lines.extend(f"{pad}{line}" for line in deferred)
        for scope in reversed(self.managed_scopes[start:]):
            for name, typ in reversed(scope):
                lines.append(f"{pad}{self.release_stmt(name, typ)}")
        return lines

    def temp(self, label: str) -> str:
        self.temp_counter += 1
        return f"__zy_{label}_{self.temp_counter}"

    @staticmethod
    def ident(value: str) -> str:
        return re.sub(r"[^A-Za-z0-9_]", "_", value)

    @staticmethod
    def c_string(value: str) -> str:
        return json.dumps(value, ensure_ascii=False)

    def struct_tag(self, name: str) -> str:
        return self.native_struct_names.get(name, f"zy2_tag_{self.ident(name)}")

    def struct_c_name(self, name: str) -> str:
        return self.native_struct_names.get(name, f"zy2_struct_{self.ident(name)}")

    def class_c_name(self, typ: Type) -> str:
        return f"zy3_class_{self.type_slug(typ)}"

    def class_payload_name(self, typ: Type) -> str:
        return f"{self.class_c_name(typ)}_payload"

    def class_handle_tag(self, typ: Type) -> str:
        return f"{self.class_c_name(typ)}_handle"

    def class_drop_name(self, typ: Type) -> str:
        return f"{self.class_c_name(typ)}_drop"
